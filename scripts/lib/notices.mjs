// REL-03: pure helpers for the third-party notice inventory (scripts/notices/generate-notices.mjs).
// Kept free of I/O so the classification and rendering are unit-tested.
import crypto from "node:crypto";

/** Supported package targets (CLAUDE.md, REL-01) and their Rust triples. */
export const TARGETS = [
  { id: "windows-x86_64", triple: "x86_64-pc-windows-msvc" },
  { id: "macos-aarch64", triple: "aarch64-apple-darwin" },
  { id: "linux-x86_64", triple: "x86_64-unknown-linux-gnu" },
];

/** Workspace binaries that ship in packages. */
export const SHIPPED_ROOTS = ["dm-desktop", "dm-service", "dm-cli", "dm-browser-host"];

/** Top-level files in a package that carry license or notice text. */
export const NOTICE_FILE = /^(licen[cs]e|copying|notice|copyright|unlicense|authors)([-._].*)?$/i;

export const normalizeText = (text) => text.replace(/\r\n?/g, "\n").replace(/\s+$/, "") + "\n";
export const textId = (text) =>
  crypto.createHash("sha256").update(normalizeText(text)).digest("hex").slice(0, 16);

/**
 * Walks one target's `cargo metadata` resolve from the shipped roots.
 * Normal edges reach distributed code; proc-macro packages and build-dependency edges are
 * build-only (they run on the build machine and are not redistributed); workspace members are the
 * project's own code. Returns { distributed: Set<id>, buildOnly: Set<id> }.
 */
export function classifyCargo(metadata, roots = SHIPPED_ROOTS) {
  const byId = new Map(metadata.packages.map((p) => [p.id, p]));
  const nodes = new Map(metadata.resolve.nodes.map((n) => [n.id, n]));
  const members = new Set(metadata.workspace_members);
  const isProcMacro = (id) =>
    byId.get(id)?.targets?.some((t) => t.kind.includes("proc-macro")) ?? false;
  const distributed = new Set();
  const buildOnly = new Set();
  const seen = new Set();
  const stack = metadata.workspace_members.filter((id) => roots.includes(byId.get(id)?.name));
  if (stack.length !== roots.length) {
    const found = stack.map((id) => byId.get(id).name);
    throw new Error(
      `shipped roots missing from the workspace: ${roots.filter((r) => !found.includes(r))}`,
    );
  }
  while (stack.length > 0) {
    const id = stack.pop();
    if (seen.has(id)) continue;
    seen.add(id);
    for (const dep of nodes.get(id)?.deps ?? []) {
      const kinds = dep.dep_kinds.map((k) => k.kind);
      if (kinds.includes(null)) {
        if (isProcMacro(dep.pkg)) markBuild(dep.pkg);
        else {
          if (!members.has(dep.pkg)) distributed.add(dep.pkg);
          stack.push(dep.pkg);
        }
      } else if (kinds.includes("build")) markBuild(dep.pkg);
    }
  }
  function markBuild(id) {
    // A build-only package and everything it pulls in (never linked into a shipped binary).
    const s = [id];
    while (s.length > 0) {
      const x = s.pop();
      if (buildOnly.has(x) || members.has(x)) continue;
      buildOnly.add(x);
      for (const d of nodes.get(x)?.deps ?? [])
        if (d.dep_kinds.some((k) => k.kind !== "dev")) s.push(d.pkg);
    }
  }
  for (const id of distributed) buildOnly.delete(id);
  return { distributed, buildOnly };
}

/** Problems that keep a distributed component's notice incomplete. */
export function unresolvedFor({ license, texts }) {
  const out = [];
  if (!license) out.push("no license expression in the package metadata");
  if (texts.length === 0) out.push("no license or notice text in the published package");
  return out;
}

/** Validates the inventory: every distributed component is listed with a version and targets. */
export function checkInventory(data) {
  const problems = [];
  for (const c of data.components) {
    if (!c.name) problems.push("a component without a name");
    if (!Array.isArray(c.targets) || c.targets.length === 0) problems.push(`${c.name}: no targets`);
    for (const t of c.texts) if (!data.texts[t]) problems.push(`${c.name}: missing text ${t}`);
    const expected = unresolvedFor(c).filter((u) => !c.unresolved.includes(u));
    if (c.ecosystem !== "toolchain" && c.ecosystem !== "installer" && expected.length > 0)
      problems.push(`${c.name}: unresolved metadata not recorded: ${expected.join("; ")}`);
  }
  return problems;
}

/** The plain-text notices file bundled with packages (stable order). */
export function renderText(data) {
  const lines = [
    "Downova — third-party notices",
    "",
    "Downova includes the third-party components listed below. Each is distributed under its own",
    "license, reproduced after the list. Generated by scripts/notices/generate-notices.mjs from",
    `Cargo.lock (sha256 ${data.inputs.cargo_lock_sha256.slice(0, 16)}…) and pnpm-lock.yaml (sha256 ${data.inputs.pnpm_lock_sha256.slice(0, 16)}…).`,
    "Components marked UNRESOLVED have incomplete license metadata; see the B3.6 report.",
    "",
    "=".repeat(78),
    "",
  ];
  for (const c of data.components) {
    lines.push(`${c.name} ${c.version ?? "(version unknown)"}`);
    lines.push(`  License: ${c.license ?? "UNKNOWN"}`);
    lines.push(`  Source: ${c.source}`);
    if (c.repository) lines.push(`  Repository: ${c.repository}`);
    lines.push(`  Targets: ${c.targets.join(", ")}`);
    for (const u of c.unresolved) lines.push(`  UNRESOLVED: ${u}`);
    for (const t of c.texts) lines.push(`  Text: [${t}] ${data.texts[t].file}`);
    lines.push("");
  }
  lines.push("=".repeat(78), "", "Not redistributed:", "");
  for (const e of data.external)
    lines.push(`- ${e.name}${e.version ? ` ${e.version}` : ""}: ${e.reason}`);
  lines.push("", "=".repeat(78), "", "License and notice texts", "");
  for (const [id, t] of Object.entries(data.texts)) {
    lines.push(
      "-".repeat(78),
      `[${id}] ${t.file} (used by: ${t.used_by.join(", ")})`,
      "-".repeat(78),
      "",
    );
    lines.push(t.text.replace(/\n$/, ""), "");
  }
  return lines.join("\n") + "\n";
}
