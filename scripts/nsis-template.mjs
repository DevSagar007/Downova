#!/usr/bin/env node
// ADR 0039: Downova's NSIS installer template is the one inside the pinned Tauri CLI plus the
// patches below, and nothing else. This script rebuilds it from the installed CLI binary.
//   node scripts/nsis-template.mjs --write   regenerate apps/desktop/src-tauri/windows/installer.nsi
//   node scripts/nsis-template.mjs --check   fail when the file differs (a CLI upgrade changed the
//                                             upstream template, or the file was edited by hand)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(root, "apps/desktop/src-tauri/windows/installer.nsi");

/** Each patch replaces exactly one occurrence of `find` in the upstream template (LF form). */
export const PATCHES = [
  {
    id: "program-folder",
    find: '      StrCpy $INSTDIR "$LOCALAPPDATA\\${PRODUCTNAME}"\n',
    replace:
      "      ; Downova (ADR 0039): program files in Programs, apart from the data folder\n" +
      '      StrCpy $INSTDIR "$LOCALAPPDATA\\Programs\\${PRODUCTNAME}"\n',
  },
  {
    id: "leave-the-data-folder",
    find:
      "Function RestorePreviousInstallLocation\n" +
      '  ReadRegStr $4 SHCTX "${MANUPRODUCTKEY}" ""\n',
    replace:
      "Function RestorePreviousInstallLocation\n" +
      '  ReadRegStr $4 SHCTX "${MANUPRODUCTKEY}" ""\n' +
      "  ; Downova (ADR 0039): an installation in the shared data folder moves to the default;\n" +
      "  ; NSIS_HOOK_PREINSTALL removes its old program files and keeps the data.\n" +
      '  ${If} $4 == "$LOCALAPPDATA\\${PRODUCTNAME}"\n' +
      '    StrCpy $4 ""\n' +
      "  ${EndIf}\n",
  },
];

const HEADER =
  "; Downova installer template (ADR 0039). Generated by scripts/nsis-template.mjs from the NSIS\n" +
  "; template in the pinned Tauri CLI (MIT OR Apache-2.0, https://github.com/tauri-apps/tauri)\n" +
  "; plus the patches listed there. Do not edit by hand: change the patches and run --write.\n";

/** The installed Tauri CLI native binary (any platform's package carries the same template). */
function cliBinary() {
  const store = path.join(root, "node_modules/.pnpm");
  for (const dir of fs.readdirSync(store).filter((d) => d.startsWith("@tauri-apps+cli-"))) {
    const pkgs = path.join(store, dir, "node_modules/@tauri-apps");
    for (const p of fs.existsSync(pkgs) ? fs.readdirSync(pkgs) : []) {
      const d = path.join(pkgs, p);
      const bin = fs.readdirSync(d).find((f) => f.endsWith(".node"));
      if (bin) return path.join(d, bin);
    }
  }
  throw new Error("no @tauri-apps/cli native binary installed (run pnpm install)");
}

/** The upstream installer.nsi embedded in the CLI binary, with LF line endings. */
export function upstreamTemplate(bin = cliBinary()) {
  const buf = fs.readFileSync(bin);
  const s = buf.toString("latin1");
  const anchor = s.search(/ManifestDPIAware true\r?\n; Add in `dpiAwareness`/);
  if (anchor < 0) throw new Error("the NSIS template was not found in " + bin);
  const start = s.lastIndexOf("Unicode true", anchor);
  if (start < 0 || anchor - start > 64) throw new Error("the template start was not found");
  const end = s.indexOf("\0", anchor);
  return buf.subarray(start, end).toString("utf8").replace(/\r\n/g, "\n");
}

export function patched(upstream) {
  let text = upstream;
  for (const p of PATCHES) {
    const count = text.split(p.find).length - 1;
    if (count !== 1)
      throw new Error(`patch ${p.id}: expected one match in the upstream template, found ${count}`);
    text = text.replace(p.find, p.replace);
  }
  // LF, like every text file in the repository (.gitattributes); makensis reads either.
  return HEADER + text;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const mode = process.argv[2];
  const want = patched(upstreamTemplate());
  if (mode === "--write") {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, want);
    console.log(`nsis template: wrote ${path.relative(root, OUT)}`);
  } else if (mode === "--check") {
    const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : null;
    if (have?.replace(/\r\n/g, "\n") !== want.replace(/\r\n/g, "\n")) {
      console.error(
        `nsis template: ${path.relative(root, OUT)} differs from the pinned Tauri CLI template plus the ADR 0039 patches; run node scripts/nsis-template.mjs --write and review the diff`,
      );
      process.exit(1);
    }
    console.log("nsis template: up to date (pinned Tauri CLI template + ADR 0039 patches)");
  } else {
    console.error("usage: node scripts/nsis-template.mjs --write|--check");
    process.exit(2);
  }
}
