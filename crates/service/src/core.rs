    /// Attaches durable storage and restores what it holds: jobs, idempotency records younger than
    /// [`IDEMPOTENCY_RETENTION_MS`], and the checkpoints of unfinished jobs. Unfinished jobs with a
    /// checkpoint this backend can use wait for [`Core::recover`]; the others fail as interrupted.
    pub fn with_store(self, mut store: Store) -> Result<Self, StorageError> {
        // Restore admission before any recovered transfer can start.
        if let Some(n) = store.load_concurrency()? {
            self.max_active.store(n as usize, Ordering::SeqCst);
        }
        // Bandwidth limits (CORE-06): the global one into the backend, each job's own into its
        // job, before any recovered transfer receives a body byte.
        if let Some(bps) = store.load_global_speed_limit()? {
            match self.backend.set_global_rate(Some(bps)) {
                Ok(()) => self.global_speed_limit.store(bps, Ordering::SeqCst),
                Err(e) => eprintln!(
                    "dm-service: the saved overall speed limit cannot be applied by this engine: {}",
                    e.detail
                ),
            }
        }
        let job_limits: HashMap<JobId, u64> = store.load_job_speed_limits()?.into_iter().collect();
        let cutoff = now_ms().saturating_sub(IDEMPOTENCY_RETENTION_MS);
        store.prune_idempotency(cutoff)?;
        // Removed jobs are kept while a retained key may still replay them (ADR 0013).
        store.purge_removed(cutoff)?;
        let removed: HashMap<JobId, u64> = store.removed_jobs()?.into_iter().collect();
        let finished: HashMap<JobId, u64> = store.finished_times()?.into_iter().collect();
        let retention_days = store.load_retention()?;
        let decided: HashSet<JobId> = store
            .notify_states()?
            .into_iter()
            .map(|(id, _)| id)
            .collect();
        let (notify_enabled, notify_locale) = store.load_notifications()?;
        let durable = support_of(&self.capabilities, Capability::DurableResume)
            == CapabilitySupport::Supported;
        let mut journal: HashMap<JobId, JournalRow> = store
            .load_journal()?
            .into_iter()
            .map(|e| (e.job_id.clone(), e))
            .collect();
        // ADR 0027: the data key and the login contexts, before any job row is read.
        let registry = credentials::startup(&mut store, &self.vault, self.vault_wait);
        // The key exists but the store is locked now: sealed links are kept for the next start.
        let store_locked = registry.store_locked;
        let mut jobs = Vec::new();
        for row in store.load_jobs()? {
            let entry = journal.remove(&row.id);
            let checkpoint = if row.phase.is_terminal() || entry.is_some() {
                None
            } else {
                store
                    .load_checkpoint(&row.id)?
                    .filter(|cp| durable && cp.backend_id == self.backend.id())
            };
            let removed_at = removed.get(&row.id).copied();
            let (mut job, changed) = Job::restore(row, checkpoint, entry, store_locked);
            if changed {
                store.update_job(&job.row())?;
            }
            job.removed_at_ms = removed_at;
            job.speed_limit = job_limits.get(&job.id).copied();
            job.finished_at_ms = finished.get(&job.id).copied();
            job.notify_decided = decided.contains(&job.id);
            job.auth = job
                .credential_id
                .as_ref()
                .and_then(|id| registry.contexts.get(id))
                .map(|c| c.info.clone());
            // A job that is terminal without a decision at startup (for example, an interrupted
            // job failed just now by the restore) is never notified: startup notifies nothing.
            if job.phase.is_terminal() && !job.notify_decided {
                store.decide_notification(&job.id, "skipped")?;
                job.notify_decided = true;
            }
            jobs.push(job);
        }
        *self
            .creds
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner) = registry;
        let idempotency = store
            .load_idempotency()?
            .into_iter()
            .map(|r| (r.key, (r.fingerprint_sha256, r.job_id)))
            .collect();
        let operations = store
            .load_operations()?
            .into_iter()
            .map(|op| (op.operation_id.clone(), op))
            .collect();
        let mut queues = store.load_queues()?;
        if !queues.iter().any(|q| q.queue_id == DEFAULT_QUEUE) {
            queues.insert(0, default_queue());
        }
        // A job whose queue disappeared (cannot happen through the service) joins the default.
        for job in &mut jobs {
            if !queues.iter().any(|q| q.queue_id == job.queue_id) {
                job.queue_id = DEFAULT_QUEUE.to_owned();
            }
            job.sync_queue_hold(queue_running(&queues, &job.queue_id));
        }
        // Schedules (CORE-08) before any recovered job can be admitted: restore, open a durable
        // catch-up for a window missed while the service was not running, then hold the jobs of
        // queues that may not run now. Nothing transfers yet, so holding is only the blocker.
        let now = self.now_ts();
        let mut schedules = HashMap::new();
        for row in store.load_queue_schedules()? {
            let Ok(schedule) = serde_json::from_str::<QueueSchedule>(&row.schedule_json) else {
                eprintln!(
                    "dm-service: queue {} has an unreadable schedule; ignored",
                    row.queue_id
                );
                continue;
            };
            let tz = jiff::tz::TimeZone::get(&schedule.timezone).unwrap_or_else(|_| {
                eprintln!(
                    "dm-service: time zone {} of queue {} is unknown here; evaluated as UTC",
                    schedule.timezone, row.queue_id
                );
                jiff::tz::TimeZone::UTC
            });
            let catch_up = match (
                row.catch_up_for_ms,
                row.catch_up_from_ms,
                row.catch_up_until_ms,
            ) {
                (Some(a), Some(b), Some(c)) => match (ms_ts(a), ms_ts(b), ms_ts(c)) {
                    (Some(for_start), Some(from), Some(until)) => Some(CatchUp {
                        for_start,
                        from,
                        until,
                    }),
                    _ => None,
                },
                _ => None,
            };
            let last_evaluated = row.evaluated_ms.and_then(ms_ts).unwrap_or(now);
            let mut rt = SchedRuntime {
                eval: sched::evaluate(&schedule, now, &tz),
                schedule,
                tz,
                catch_up,
                last_evaluated,
                persisted_at: now,
            };
            if let Some(missed) = sched::last_missed_window(
                &rt.schedule,
                &rt.tz,
                rt.last_evaluated,
                now,
                rt.catch_up.map(|c| c.for_start),
            ) && let Some(until) = sched::catch_up_until(missed, now)
            {
                // Durable before it takes effect: a restart finds it and never repeats it.
                match store.save_catch_up(
                    &row.queue_id,
                    ts_ms(missed.start),
                    ts_ms(now),
                    ts_ms(until),
                ) {
                    Ok(()) => {
                        rt.catch_up = Some(CatchUp {
                            for_start: missed.start,
                            from: now,
                            until,
                        });
                    }
                    Err(e) => eprintln!("dm-service: catch-up not recorded, so not opened: {e}"),
                }
            }
            rt.last_evaluated = now;
            let _ = store.save_schedules_evaluated(ts_ms(now));
            schedules.insert(row.queue_id.clone(), rt);
        }
        for job in &mut jobs {
            if let Some(rt) = schedules.get(&job.queue_id) {
                job.sync_schedule_hold(rt.eligible(now));
            }
        }
        let (rules, collision) = store.load_settings()?;
        self.ask_on_collision
            .store(collision == CollisionPolicy::Ask, Ordering::SeqCst);
        {
            let mut state = self
                .state
                .try_lock()
                .map_err(|_| StorageError::Open("the coordinator is already in use".to_owned()))?;
            state.jobs = jobs;
            state.schedules = schedules;
            state.idempotency = idempotency;
            state.queues = queues;
            state.rules = rules;
            state.retention_days = retention_days;
            state.operations = operations;
            state.notify_enabled = notify_enabled;
            state.notify_locale = if notify_locale == "bn" {
                NotificationLocale::Bn
            } else {
                NotificationLocale::En
            };
            state.store = Some(store);
        }
        Ok(self)
    }

    /// Continues the unfinished jobs restored with a checkpoint (call once, after [`with_store`]).
    /// Each gets a new service-owned attempt; the backend re-verifies the confirmed data before
    /// anything is reused. Paused jobs stay paused. Returns how many jobs were restored.
    ///
    /// [`with_store`]: Core::with_store
    pub async fn recover(&self) -> usize {
        let mut guard = self.state.lock().await;
        let State {
            jobs,
            store,
            queues,
            ..
        } = &mut *guard;
        let mut restored = 0usize;
        // 1. Unfinished finalizations first (B1.3): their files are already complete.
        for job in jobs.iter_mut() {
            if !std::mem::take(&mut job.recover_journal) {
                continue;
            }
            let Some(entry) = job.finalizing.clone() else {
                continue;
            };
            trace("journal_reconcile", &job.id, Some(&entry.attempt_id), 0);
            self.run_finalization(store, job, entry, true).await;
            restored = restored.saturating_add(1);
            if let Ok(mut s) = self.startup.lock() {
                s.journal_reconciled = s.journal_reconciled.saturating_add(1);
            }
        }
        // 2. Transfers with a durable checkpoint.
        for job in jobs.iter_mut() {
            let Some(cp) = job.recover_from.take() else {
                continue;
            };
            if job.credential_id.is_some() && self.session_for(job).is_none() {
                // ADR 0028: restoring would rebuild the transfer without its session. The
                // checkpoint and partial data wait for a reconnect (or an unlocked store).
                job.recover_from = Some(cp);
                let error = self.sign_in_error(job);
                self.hold_for_sign_in(store, job, error).await;
                continue;
            }
            if self.restore_from_checkpoint(store, job, cp).await {
                restored = restored.saturating_add(1);
                if let Ok(mut s) = self.startup.lock() {
                    s.checkpoints_restored = s.checkpoints_restored.saturating_add(1);
                }
            }
        }
        // Recovered jobs transfer only through admission, within the limits.
        self.admit(jobs, queues, store).await;
        restored
    }

    /// Gives `job` a new attempt restored from `cp` (the backend re-verifies the data), moves the
    /// checkpoint to it atomically and resumes it unless the user paused the job. A refused
    /// restore fails the job explicitly. Returns whether the job was restored.
    async fn restore_from_checkpoint(
        &self,
        store: &mut Option<Store>,
        job: &mut Job,
        cp: CheckpointRow,
    ) -> bool {
        let attempt_id = new_attempt_id();
        let request = self.request_for(job, attempt_id.clone());
        let stored = DurableCheckpoint {
            backend: cp.backend_id.clone(),
            format_version: cp.format_version,
            confirmed: cp.confirmed,
            payload: cp.payload.clone(),
        };
        let handle = match self.backend.restore(request, &stored).await {
            Ok(handle) => handle,
            Err(e) => {
                job.fail(recovery_error(&e));
                persist(store, job);
                trace("recovery_failed", &job.id, None, 0);
                return false;
            }
        };
        job.attempt = Some(Attempt {
            id: attempt_id.clone(),
            handle: handle.clone(),
        });
        let moved = CheckpointRow {
            attempt_id: attempt_id.clone(),
            updated_at_ms: now_ms(),
            ..cp.clone()
        };
        if let Some(s) = store.as_mut()
            && let Err(e) = s.rebind_checkpoint(&job.row(), &moved, &cp.attempt_id)
        {
            eprintln!(
                "dm-service: could not record the recovery of job {}: {e}",
                job.id
            );
        }
        job.stored_attempt = None;
        job.durable = cp.confirmed.0;
        job.downloaded = cp.confirmed;
        trace("recovered", &job.id, Some(&attempt_id), cp.confirmed.0);
        // The restored attempt is paused; it transfers when admitted (B1.5), never before.
        let _ = handle;
        if job.desired_state == DesiredState::Running {
            job.queue(Pending::Resume);
        }
        true
    }

    /// The backend stopped a transfer with `DISK_FULL` / `VOLUME_MISSING` (B1.4). Commits its last
    /// durable checkpoint, releases the attempt (keeping its partial file; with nothing confirmed
    /// the unconfirmed partial is removed, which loses no progress), and holds the job with the
    /// matching blocker. The desired state is kept.
    async fn block_on_disk(
        &self,
        store: &mut Option<Store>,
        job: &mut Job,
        e: BackendError,
        now: tokio::time::Instant,
    ) {
        self.take_checkpoint(store, job).await;
        let Some(attempt) = job.attempt.take() else {
            return;
        };
        let checkpoint = store
            .as_ref()
            .and_then(|s| s.load_checkpoint(&job.id).ok().flatten())
            .filter(|cp| cp.attempt_id == attempt.id);
        if checkpoint.is_some() {
            let _ = self.backend.remove(&attempt.handle).await;
            job.stored_attempt = Some(attempt.id.clone());
        } else {
            // Nothing durable: those bytes could never be trusted for a resume.
            let _ = self.backend.discard(&attempt.handle).await;
            job.stored_attempt = None;
            job.durable = 0;
            job.downloaded = ByteCount(0);
        }
        job.recover_from = checkpoint;
        job.phase = Phase::Queued;
        job.blockers = disk_blocker(e.kind).into_iter().collect();
        job.error = Some(disk_error(&e));
        job.disk_check_at = Some(now.checked_add(DISK_RECHECK_INTERVAL).unwrap_or(now));
        persist(store, job);
        trace("disk_blocked", &job.id, Some(&attempt.id), job.durable);
    }

    /// Why a signed-in job cannot run without a reconnect, from its context's state.
    fn sign_in_error(&self, job: &Job) -> ErrorData {
        use dm_domain::api::CredentialState as S;
        let state = job
            .credential_id
            .as_ref()
            .and_then(|id| self.creds().contexts.get(id).map(|c| c.info.state))
            .or(job.auth.as_ref().map(|a| a.state));
        let (kind, action, detail) = match state {
            Some(S::Locked) => (
                ErrorKind::CredentialStoreUnavailable,
                NextAction::Retry,
                "the system credential store is locked; unlock it and restart Downova, or reconnect the download from the browser",
            ),
            Some(S::Expired) => (
                ErrorKind::AuthRequired,
                NextAction::SignIn,
                "the website no longer accepts this sign-in; sign in there and reconnect the download from the browser",
            ),
            Some(S::Forgotten) => (
                ErrorKind::AuthRequired,
                NextAction::SignIn,
                "this sign-in was forgotten; reconnect the download from the browser to continue",
            ),
            _ => (
                ErrorKind::AuthRequired,
                NextAction::SignIn,
                "this download's sign-in is not available; reconnect it from the browser",
            ),
        };
        ErrorData {
            kind,
            retryable: kind == ErrorKind::CredentialStoreUnavailable,
            next_action: action,
            detail: Some(detail.into()),
        }
    }

    /// The site rejected the session (ADR 0028): its context is expired for every job using it;
    /// the secret is dropped from memory (a remembered entry stays until it is replaced or
    /// forgotten, so a reconnect can retire it consistently).
    fn expire_context(&self, store: &mut Option<Store>, job: &mut Job) {
        use dm_domain::api::CredentialState as S;
        let Some(id) = job.credential_id.clone() else {
            return;
        };
        if let Some(c) = self.creds().contexts.get_mut(&id) {
            c.scope = None;
            c.info.state = S::Expired;
        }
        if let Some(a) = job.auth.as_mut() {
            a.state = S::Expired;
        }
        if let Some(s) = store.as_mut() {
            let _ = s.set_credential_state(&id, "expired");
        }
    }

    /// Holds a signed-in job until it is reconnected (ADR 0028), the way a disk hold works: the
    /// attempt's last durable checkpoint is committed and the attempt released while its partial
    /// file is kept (without anything durable the unconfirmed bytes are removed, which loses no
    /// resumable progress). The desired state is kept; nothing is retried on its own.
    async fn hold_for_sign_in(&self, store: &mut Option<Store>, job: &mut Job, error: ErrorData) {
        if let Some(handle) = job.attempt.as_ref().map(|a| a.handle.clone()) {
            let _ = self.backend.pause(&handle).await;
            self.take_checkpoint(store, job).await;
            if let Some(attempt) = job.attempt.take() {
                let checkpoint = store
                    .as_ref()
                    .and_then(|s| s.load_checkpoint(&job.id).ok().flatten())
                    .filter(|cp| cp.attempt_id == attempt.id);
                if checkpoint.is_some() {
                    let _ = self.backend.remove(&attempt.handle).await;
                    job.stored_attempt = Some(attempt.id.clone());
                } else {
                    let _ = self.backend.discard(&attempt.handle).await;
                    job.stored_attempt = None;
                    job.durable = 0;
                    job.downloaded = ByteCount(0);
                }
                job.recover_from = checkpoint;
            }
        }
        // The stored row stays bound to the checkpoint's attempt, so the checkpoint is kept; the
        // job shows what is actually kept (the durable part), not the last progress seen.
        if let Some(cp) = &job.recover_from {
            job.stored_attempt = Some(cp.attempt_id.clone());
            job.downloaded = cp.confirmed;
            job.durable = cp.confirmed.0;
        }
        job.pending = None;
        job.retry_at = None;
        job.phase = Phase::Queued;
        job.blockers.retain(|b| is_queue_policy(*b));
        job.blockers.push(Blocker::SignInRequired);
        job.error = Some(error);
        persist(store, job);
        trace("sign_in_hold", &job.id, None, job.durable);
    }

    /// A job waiting for space: when due, checks the budget for what it still needs and, if it
    /// fits, continues it (restore from its checkpoint, or a fresh start).
    async fn recheck_disk(
        &self,
        store: &mut Option<Store>,
        job: &mut Job,
        now: tokio::time::Instant,
    ) {
        if job.disk_check_at.is_some_and(|at| at > now) {
            return;
        }
        job.disk_check_at = Some(now.checked_add(DISK_RECHECK_INTERVAL).unwrap_or(now));
        let needed = job.total.map_or(0, |t| t.0.saturating_sub(job.durable));
        if let Err(e) = self.space.ensure(&job.destination, needed) {
            let changed = job.error.as_ref().map(|d| (d.kind, d.detail.clone()))
                != Some((e.kind, Some(e.detail.clone())));
            job.blockers = disk_blocker(e.kind).into_iter().collect();
            job.error = Some(disk_error(&e));
            if changed {
                persist(store, job);
            }
            return;
        }
        job.blockers.clear();
        job.error = None;
        trace("disk_ok", &job.id, None, job.durable);
        match job.recover_from.take() {
            Some(cp) => {
                self.restore_from_checkpoint(store, job, cp).await;
            }
            None => job.queue(Pending::Fresh),
        }
    }

    /// Graceful shutdown: stops every running transfer (the backend flushes and syncs) and commits
    /// its checkpoint, keeping the job's desired state so it continues after the next start.
    pub async fn prepare_shutdown(&self) {
        let mut guard = self.state.lock().await;
        let State { jobs, store, .. } = &mut *guard;
        for job in jobs.iter_mut() {
            if job.phase.is_terminal() || job.desired_state != DesiredState::Running {
                continue;
            }
            let Some(handle) = job.attempt.as_ref().map(|a| a.handle.clone()) else {
                continue;
            };
            if let Err(e) = self.backend.pause(&handle).await {
                eprintln!(
                    "dm-service: could not stop job {} for shutdown: {e}",
                    job.id
                );
                continue;
            }
            self.take_checkpoint(store, job).await;
        }
    }

    /// Exports the current attempt's checkpoint and commits it with the job row when it covers more
    /// than the last committed one. Failures are reported, never treated as durable.
    async fn take_checkpoint(&self, store: &mut Option<Store>, job: &mut Job) -> bool {
        let Some(attempt) = job.attempt.as_ref() else {
            return false;
        };
        let (attempt_id, handle) = (attempt.id.clone(), attempt.handle.clone());
        let cp = match self.backend.checkpoint(&handle).await {
            Ok(Some(cp)) if cp.confirmed.0 > job.durable => cp,
            Ok(_) => return false,
            Err(e) => {
                eprintln!("dm-service: no checkpoint for job {}: {e}", job.id);
                return false;
            }
        };
        let Some(s) = store.as_mut() else {
            return false;
        };
        let row = CheckpointRow {
            job_id: job.id.clone(),
            attempt_id: attempt_id.clone(),
            backend_id: cp.backend,
            backend_version: self.backend_version.clone(),
            format_version: cp.format_version,
            confirmed: cp.confirmed,
            payload: cp.payload,
            updated_at_ms: now_ms(),
        };
        match s.save_checkpoint(&job.row(), &row) {
            Ok(()) => {
                job.durable = cp.confirmed.0;
                trace("checkpoint", &job.id, Some(&attempt_id), cp.confirmed.0);
                true
            }
            Err(e) => {
                eprintln!("dm-service: checkpoint for job {} not saved: {e}", job.id);
                false
            }
        }
    }

    fn request_for(&self, job: &Job, attempt_id: AttemptId) -> TransferRequest {
        let connections = match support_of(&self.capabilities, Capability::SegmentedHttp) {
            CapabilitySupport::Supported => SEGMENTED_CONNECTIONS,
            _ => 1,
        };
        TransferRequest {
            attempt_id,
            url: job.url.clone(),
            headers: Vec::new(),
            destination_dir: job.destination.clone(),
            file_name: job.staging_name.clone(),
            max_connections: connections,
            // Restored with the job before recovery: every attempt (fresh, retried, recovered) is
            // limited from its first body byte (CORE-06).
            rate_limit: job.speed_limit,
            session: self.session_for(job),
        }
    }

