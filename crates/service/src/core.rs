    async fn poll_job(&self, job: &mut Job, now: tokio::time::Instant) {
        let Some(attempt) = &job.attempt else {
            if job.retry_at.is_some_and(|at| at <= now) {
                job.retry_at = None;
                // The cool-down ends; queue and schedule holds stay (CORE-08: a retry never
                // starts outside its window or in a stopped queue).
                job.blockers.retain(|b| is_queue_policy(*b));
                job.queue(Pending::Fresh);
            }
            return;
        };
        let (attempt_id, handle) = (attempt.id.clone(), attempt.handle.clone());
        match self.backend.progress(&handle).await {
            // Disk full / drive missing: recoverable when the backend can resume durably (B1.4).
            Ok(BackendProgress {
                state: TransferState::Failed(e),
                ..
            }) if disk_blocker(e.kind).is_some()
                && support_of(&self.capabilities, Capability::DurableResume)
                    == CapabilitySupport::Supported =>
            {
                job.disk_failure = Some(e);
            }
            // ADR 0028: the site rejected the session of a signed-in download. Never retried on
            // its own (no retry storm); the poll loop holds it, keeping its partial data.
            Ok(BackendProgress {
                state: TransferState::Failed(e),
                ..
            }) if e.kind == ErrorKind::AuthRequired && job.credential_id.is_some() => {
                job.auth_failure = Some(e);
            }
            Ok(BackendProgress {
                state: TransferState::Failed(e),
                ..
            }) => self.after_failure(job, e, now).await,
            Ok(progress) => apply_progress(job, &attempt_id, progress).await,
            Err(e) => job.fail(ServiceError::from(e).0),
        }
    }

    /// A failed attempt either schedules a fresh one (transient kinds, within the policy) or
    /// fails the job.
    async fn after_failure(&self, job: &mut Job, e: BackendError, now: tokio::time::Instant) {
        let decision = decide_retry(
            &self.retry_policy,
            e.kind,
            job.retries,
            e.retry_after,
            jitter_sample(),
        );
        let busy = e.kind == ErrorKind::ServerBusy;
        let error = ServiceError::from(e).0;
        let RetryDecision::RetryAfter(delay) = decision else {
            job.fail(error);
            return;
        };
        if let Some(attempt) = &job.attempt
            && self.backend.discard(&attempt.handle).await.is_err()
        {
            // Without discarding, a new attempt could resume the partial without a validator.
            job.fail(error);
            return;
        }
        job.attempt = None;
        job.retries = job.retries.saturating_add(1);
        job.downloaded = ByteCount(0);
        job.phase = Phase::Queued;
        job.error = Some(error);
        job.retry_at = Some(now.checked_add(delay).unwrap_or(now));
        // The discarded attempt took its checkpoint with it: a kill before the next attempt's first
        // checkpoint ends this job as interrupted (observable for the kill tests).
        trace("retry_scheduled", &job.id, None, 0);
        job.blockers.retain(|b| is_queue_policy(*b));
        if busy {
            job.blockers.push(Blocker::RateLimitCooldown);
        }
    }

