/// A queue's schedule at run time (CORE-08, ADR 0025).
#[derive(Debug, Clone)]
struct SchedRuntime {
    schedule: QueueSchedule,
    tz: jiff::tz::TimeZone,
    /// The last evaluation (refreshed by the poll loop at every change and at least every 60 s).
    eval: sched::Evaluation,
    catch_up: Option<CatchUp>,
    /// When the schedule was last evaluated (missed-window detection after a restart).
    last_evaluated: Timestamp,
    /// When the evaluation time was last written (sparingly; see `SCHEDULE_PERSIST_EVERY`).
    persisted_at: Timestamp,
}

/// An open catch-up window (ADR 0025 §5): absolute instants, stored before it takes effect.
#[derive(Debug, Clone, Copy)]
struct CatchUp {
    /// Start instant of the missed window it replaces: its identity.
    for_start: Timestamp,
    from: Timestamp,
    until: Timestamp,
}

/// The schedules' wall clock (a closure, so tests can drive time).
#[derive(Clone)]
struct Clock(Arc<dyn Fn() -> Timestamp + Send + Sync>);

impl std::fmt::Debug for Clock {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("Clock")
    }
}

/// Bound on how stale an evaluation may get (clock changes are caught within this).
const SCHEDULE_RECHECK: jiff::SignedDuration = jiff::SignedDuration::from_secs(60);
/// How often the evaluation time is written while the service runs (and at shutdown).
const SCHEDULE_PERSIST_EVERY: jiff::SignedDuration = jiff::SignedDuration::from_mins(5);

impl SchedRuntime {
    /// A catch-up window is open: its interval holds `now` (a clock set back before its start
    /// ends it; a restart cannot extend it).
    fn catching_up(&self, now: Timestamp) -> bool {
        self.catch_up
            .is_some_and(|c| c.from <= now && now < c.until)
    }
    /// The queue may run now: inside a window, inside a catch-up window, or disabled.
    fn eligible(&self, now: Timestamp) -> bool {
        sched::evaluate(&self.schedule, now, &self.tz).in_window || self.catching_up(now)
    }
}

fn ts_ms(t: Timestamp) -> u64 {
    u64::try_from(t.as_millisecond()).unwrap_or(0)
}
fn ms_ts(ms: u64) -> Option<Timestamp> {
    Timestamp::from_millisecond(i64::try_from(ms).ok()?).ok()
}

/// `info` with its schedule and the schedule's state at `now`.
fn with_schedule(mut info: QueueInfo, rt: Option<&SchedRuntime>, now: Timestamp) -> QueueInfo {
    if let Some(rt) = rt {
        let eval = sched::evaluate(&rt.schedule, now, &rt.tz);
        let catching = rt.catching_up(now);
        let until = rt.catch_up.filter(|_| catching).map(|c| c.until);
        info.schedule = Some(rt.schedule.clone());
        info.schedule_state = Some(ScheduleState {
            in_window: eval.in_window || catching,
            next_change_at: if catching && !eval.in_window {
                until.map(|u| u.to_string())
            } else {
                eval.next_change.map(|n| n.to_string())
            },
            catch_up_until: until.map(|u| u.to_string()),
        });
    }
    info
}

fn queue_info(q: &QueueRow) -> QueueInfo {
    QueueInfo {
        queue_id: q.queue_id.clone(),
        name: q.name.clone(),
        position: q.position,
        max_active: q.max_active,
        running: q.running,
        schedule: None,
        schedule_state: None,
    }
}

/// Persists several jobs at once (reorder, queue moves). A failed write is reported, not undone.
fn persist_many(store: &mut Option<Store>, jobs: &[&Job]) {
    if let Some(store) = store
        && let Err(e) = store.update_jobs(&jobs.iter().map(|j| j.row()).collect::<Vec<_>>())
    {
        eprintln!("dm-service: could not record {} job(s): {e}", jobs.len());
    }
}

fn find_job<'a>(jobs: &'a mut [Job], id: &JobId) -> Result<&'a mut Job, ServiceError> {
    jobs.iter_mut()
        .find(|j| &j.id == id)
        .ok_or_else(|| ServiceError::new(ErrorKind::InvalidRequest, format!("unknown job {id}")))
}

impl State {
    fn job_mut(&mut self, id: &JobId) -> Result<&mut Job, ServiceError> {
        find_job(&mut self.jobs, id)
    }
}

/// Writes a job's state. A failed write is reported on stderr (never with the URL) and does not
/// undo the change in memory.
/// CORE-09: records one decision per terminal outcome and returns the notices to show. Only
/// completed and failed outcomes notify, only while enabled and listed; cancellations (the user's
/// own action) and anything else are skipped. A decision the store refuses to record is retried
/// on the next poll and nothing is shown meanwhile.
fn decide_notifications(state: &mut State) -> Vec<Notice> {
    let (enabled, locale) = (state.notify_enabled, state.notify_locale);
    let State { jobs, store, .. } = state;
    let mut notices = Vec::new();
    for job in jobs.iter_mut() {
        if job.notify_decided || !job.phase.is_terminal() || job.finalizing.is_some() {
            continue;
        }
        let kind = match job.phase {
            Phase::Completed => Some(NoticeKind::Completed),
            Phase::Failed => Some(NoticeKind::Failed),
            _ => None,
        };
        let send = enabled && job.removed_at_ms.is_none() && kind.is_some();
        let recorded = match store.as_mut() {
            Some(s) => {
                match s.decide_notification(&job.id, if send { "sent" } else { "skipped" }) {
                    Ok(fresh) => Some(fresh),
                    Err(e) => {
                        eprintln!(
                            "dm-service: notification decision for job {} not recorded: {e}",
                            job.id
                        );
                        None
                    }
                }
            }
            None => Some(true),
        };
        let Some(fresh) = recorded else { continue };
        job.notify_decided = true;
        // Evidence for process and packaged tests (no name, no URL).
        if fresh {
            trace(
                if send {
                    "notify_sent"
                } else {
                    "notify_skipped"
                },
                &job.id,
                None,
                0,
            );
        }
        if fresh
            && send
            && let Some(kind) = kind
        {
            notices.push(notify::notice(kind, locale, &job.display_name));
        }
    }
    notices
}

fn persist(store: &mut Option<Store>, job: &Job) {
    if let Some(store) = store
        && let Err(e) = store.update_job(&job.row())
    {
        eprintln!("dm-service: could not record job {}: {e}", job.id);
    }
}

fn now_ms() -> u64 {
    let now = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_or(0, |d| u64::try_from(d.as_millis()).unwrap_or(u64::MAX));
    now.saturating_add(test_clock_offset_ms())
}

/// Debug builds only: `DOWNOVA_TEST_NOW_OFFSET_MS` moves the service's wall clock forward, so
/// process tests can let retention periods pass (B2.12). Always 0 in release builds.
fn test_clock_offset_ms() -> u64 {
    #[cfg(debug_assertions)]
    {
        std::env::var("DOWNOVA_TEST_NOW_OFFSET_MS")
            .ok()
            .and_then(|v| v.parse().ok())
            .unwrap_or(0)
    }
    #[cfg(not(debug_assertions))]
    {
        0
    }
}

