/// What admission does for a pending job.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Pending {
    /// Start a new attempt.
    Fresh,
    /// Resume the job's existing (paused or just restored) attempt.
    Resume,
}

impl Job {
    fn row(&self) -> JobRow {
        JobRow {
            id: self.id.clone(),
            url: self.url.clone(),
            display_name: self.display_name.clone(),
            staging_name: self.staging_name.clone(),
            name_source: self.name_source.map(|s| s.as_str().to_owned()),
            destination: self.destination.clone(),
            desired_state: self.desired_state,
            phase: self.phase,
            downloaded: self.downloaded,
            total: self.total,
            expected_sha256: self.expected_sha256.clone(),
            error: self.error.clone(),
            attempt_id: self
                .attempt
                .as_ref()
                .map(|a| a.id.clone())
                .or_else(|| self.stored_attempt.clone()),
            verification: self.verification.clone(),
            created_at_ms: self.created_at_ms,
            updated_at_ms: now_ms(),
            queue_id: self.queue_id.clone(),
            priority: self.priority,
            queue_position: self.queue_position,
            category: self.category,
            name_confirmed: self.name_confirmed,
        }
    }

    /// Rebuilds a job from its stored row. An unfinished job with a usable checkpoint waits for
    /// [`Core::recover`]; one without fails as interrupted. Returns whether the row changed.
    fn restore(
        row: JobRow,
        checkpoint: Option<CheckpointRow>,
        journal: Option<JournalRow>,
    ) -> (Self, bool) {
        let mut job = Self {
            id: row.id,
            url: row.url,
            display_name: row.display_name,
            staging_name: row.staging_name,
            // An unknown stored source cannot come from this build's schema; keep the name frozen.
            name_source: row
                .name_source
                .as_deref()
                .map(|s| naming::Source::parse(s).unwrap_or(naming::Source::Legacy)),
            naming_seen: None,
            destination: row.destination,
            desired_state: row.desired_state,
            phase: row.phase,
            downloaded: row.downloaded,
            total: row.total,
            expected_sha256: row.expected_sha256,
            attempt: None,
            error: row.error,
            retries: 0,
            retry_at: None,
            blockers: Vec::new(),
            created_at_ms: row.created_at_ms,
            durable: 0,
            checkpointed_at: None,
            recover_from: None,
            verification: row.verification,
            finalizing: None,
            recover_journal: false,
            stored_attempt: None,
            disk_failure: None,
            disk_check_at: None,
            pending: None,
            removed_at_ms: None,
            finished_at_ms: None,
            queue_id: row.queue_id,
            priority: row.priority,
            queue_position: row.queue_position,
            category: row.category,
            name_confirmed: row.name_confirmed,
        };
        if !job.name_confirmed && !job.phase.is_terminal() {
            job.blockers.push(Blocker::NameConflict);
        }
        if let Some(entry) = journal {
            // Finalization was under way: reconciled before anything else (B1.3).
            job.stored_attempt = Some(entry.attempt_id.clone());
            if !job.phase.is_terminal() {
                job.phase = Phase::Verifying;
                job.error = None;
            }
            job.finalizing = Some(entry);
            job.recover_journal = true;
            return (job, false);
        }
        if job.phase.is_terminal() {
            return (job, false);
        }
        if let Some(cp) = checkpoint {
            job.phase = Phase::Queued;
            job.error = None;
            job.downloaded = cp.confirmed;
            job.durable = cp.confirmed.0;
            job.recover_from = Some(cp);
            return (job, false);
        }
        // Accepted but never started (e.g. still waiting for a slot): it simply waits again.
        if row.attempt_id.is_none()
            && job.phase == Phase::Queued
            && (job.error.is_none() || job.desired_state == DesiredState::Paused)
        {
            job.queue(Pending::Fresh);
            return (job, false);
        }
        // Waiting for disk space with nothing confirmed yet: there is no progress to lose, so it
        // simply waits again (and starts afresh once the space is there).
        if let Some(blocker) = job.error.as_ref().and_then(|e| disk_blocker(e.kind)) {
            job.phase = Phase::Queued;
            job.blockers = vec![blocker];
            return (job, false);
        }
        job.fail(ErrorData {
            kind: ErrorKind::ServiceUnavailable,
            retryable: false,
            next_action: NextAction::None,
            detail: Some(INTERRUPTED.to_owned()),
        });
        (job, true)
    }

    /// What a durable write must capture; a changed byte count alone does not trigger one.
    #[allow(clippy::type_complexity)]
    fn checkpoint_key(
        &self,
    ) -> (
        Phase,
        DesiredState,
        Option<ErrorKind>,
        Option<ByteCount>,
        Option<AttemptId>,
    ) {
        (
            self.phase,
            self.desired_state,
            self.error.as_ref().map(|e| e.kind),
            self.total,
            self.attempt.as_ref().map(|a| a.id.clone()),
        )
    }
    /// Occupies an active-file slot: a live attempt the user wants running, not finalizing, not
    /// waiting for admission, disk space or a retry (B1.5).
    fn is_active(&self) -> bool {
        self.attempt.is_some()
            && self.desired_state == DesiredState::Running
            && !self.phase.is_terminal()
            && self.phase != Phase::Verifying
            && self.pending.is_none()
            && !self.is_disk_blocked()
    }

    /// Marks the job ready to transfer; [`Core::admit`] starts it when a slot is free.
    fn queue(&mut self, how: Pending) {
        self.pending = Some(how);
        self.phase = Phase::Queued;
        if !self.blockers.contains(&Blocker::QueueLimit) {
            self.blockers.push(Blocker::QueueLimit);
        }
    }

    /// Held by the disk policy (B1.4).
    fn is_disk_blocked(&self) -> bool {
        self.blockers
            .iter()
            .any(|b| matches!(b, Blocker::DiskUnavailable | Blocker::VolumeMissing))
    }

    fn snapshot(&self) -> DownloadSnapshot {
        DownloadSnapshot {
            job_id: self.id.clone(),
            attempt_id: self.attempt.as_ref().map(|a| a.id.clone()),
            display_name: self.display_name.clone(),
            source_display: redact_url(&self.url),
            desired_state: self.desired_state,
            phase: self.phase,
            blockers: self.blockers.clone(),
            downloaded_bytes: self.downloaded,
            total_bytes: self.total,
            error: self.error.clone(),
            verification: self.verification.clone(),
            removed: self.removed_at_ms.is_some(),
            queue_id: Some(self.queue_id.clone()),
            priority: Some(self.priority),
            queue_position: Some(ByteCount(u64::try_from(self.queue_position).unwrap_or(0))),
            category: self.category,
        }
    }

    /// Waiting for the user to confirm its final name (ask-on-collision).
    fn is_name_held(&self) -> bool {
        self.blockers.contains(&Blocker::NameConflict)
    }

    /// Applies its queue's running state: `queue_stopped` is present exactly while the queue is
    /// stopped and the job is unfinished. Never touches `desired_state`.
    fn sync_queue_hold(&mut self, running: bool) {
        let held = self.blockers.contains(&Blocker::QueueStopped);
        if !running && !self.phase.is_terminal() {
            if !held {
                self.blockers.push(Blocker::QueueStopped);
            }
        } else if held {
            self.blockers.retain(|b| *b != Blocker::QueueStopped);
        }
    }

    fn fail(&mut self, error: ErrorData) {
        self.phase = Phase::Failed;
        self.error = Some(error);
    }
}

