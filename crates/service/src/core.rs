    pub async fn add(&self, params: AddDownloadParams) -> Result<DownloadSnapshot, ServiceError> {
        // ADR 0027: a link with protected parts is sealed when persisted; create the key first.
        if dm_storage::url_has_protected_parts(&params.source.url) {
            self.ensure_data_key().await;
        }
        self.add_with(params, None).await
    }

    async fn add_with(
        &self,
        params: AddDownloadParams,
        auth: Option<dm_domain::api::AuthInfo>,
    ) -> Result<DownloadSnapshot, ServiceError> {
        validate_idempotency_key(&params.idempotency_key)?;
        let fingerprint = fingerprint_sha256(&params);
        let mut state = self.state.lock().await;

        if let Some((existing_fp, job_id)) = state.idempotency.get(&params.idempotency_key) {
            if *existing_fp != fingerprint {
                return Err(ServiceError::new(
                    ErrorKind::IdempotencyConflict,
                    "idempotency key was already used for a different request",
                ));
            }
            let job_id = job_id.clone();
            return Ok(state.job_mut(&job_id)?.snapshot());
        }
        if self.is_stopping() {
            return Err(stopping());
        }
        // ADR 0030: nothing new starts while an update is being prepared.
        self.refuse_while_updating()?;

        let scheme = url_scheme(&params.source.url)?;
        let required = if scheme == "https" {
            Capability::Https
        } else {
            Capability::Http
        };
        // Input validation first, so a malformed request is reported as such even while the
        // capability is unavailable.
        let dir = self
            .profiles
            .get(&params.destination_profile_id)
            .ok_or_else(|| {
                ServiceError::new(ErrorKind::InvalidRequest, "unknown destination profile")
            })?;
        if let Some(sha) = &params.expected_sha256
            && (sha.len() != 64 || !sha.bytes().all(|b| b.is_ascii_hexdigit()))
        {
            return Err(ServiceError::new(
                ErrorKind::InvalidRequest,
                "expected_sha256 must be 64 hex digits",
            ));
        }
        let queue_id = params
            .queue_id
            .clone()
            .unwrap_or_else(|| DEFAULT_QUEUE.to_owned());
        if !state.queues.iter().any(|q| q.queue_id == queue_id) {
            return Err(ServiceError::new(
                ErrorKind::InvalidRequest,
                "unknown queue",
            ));
        }
        // Gate before creating anything: a refused request leaves no job and no idempotency
        // record, so the same key can succeed once the capability is promoted.
        require_capability(&self.capabilities, required)?;
        let speed_limit = check_speed_limit(params.speed_limit_bytes_per_second)
            .map_err(|why| ServiceError::new(ErrorKind::InvalidRequest, why))?;
        if speed_limit.is_some() {
            require_capability(&self.capabilities, Capability::SpeedLimitPerJob)?;
        }
        // Duplicates (ADR 0015): decided under the coordinator lock, after the idempotency
        // replay, so concurrent submissions of one link cannot both pass a `refuse`.
        if params.on_duplicate.unwrap_or_default() == DuplicatePolicy::Refuse
            && !duplicates(&state.jobs, &params.source.url).is_empty()
        {
            return Err(ServiceError::new(
                ErrorKind::DuplicateDownload,
                "the same link is already in the download list",
            ));
        }

        // The staging name is fixed now and doubles as the provisional final name (B1.6). The
        // folder comes from the category's rule, fixed with the job (ADR 0015).
        let (provisional, _) = naming::provisional(&params.source.url);
        let category = params
            .category
            .unwrap_or_else(|| FileCategory::of_name(&provisional));
        let dir = state
            .rules
            .iter()
            .find(|r| r.category == category)
            .map_or_else(|| dir.clone(), |r| PathBuf::from(&r.directory));
        let dir = &dir;
        let taken = taken_names(&state.jobs, dir, None);
        let limits = Limits::native();
        let fitted = naming::fit(&provisional, dir, limits);
        let staging_name = naming::unique(dir, &fitted, &taken, None, limits);
        // Under `ask`, a provisional name that had to change is confirmed before placement.
        let name_confirmed = !(self.ask() && naming::key(&staging_name) != naming::key(&fitted));
        let queue_position = state
            .jobs
            .iter()
            .filter(|j| j.queue_id == queue_id)
            .map(|j| j.queue_position)
            .max()
            .unwrap_or(0)
            .saturating_add(1);
        let mut job = Job {
            id: new_job_id(),
            url: params.source.url.clone(),
            display_name: staging_name.clone(),
            staging_name,
            name_source: None,
            naming_seen: None,
            destination: dir.clone(),
            desired_state: DesiredState::Running,
            phase: Phase::Queued,
            downloaded: ByteCount(0),
            total: params.expected_size_bytes,
            expected_sha256: params.expected_sha256.map(|s| s.to_ascii_lowercase()),
            attempt: None,
            error: None,
            retries: 0,
            retry_at: None,
            blockers: Vec::new(),
            created_at_ms: now_ms(),
            durable: 0,
            checkpointed_at: None,
            schedule_exempt: false,
            scan: None,
            credential_id: auth.as_ref().map(|a| a.credential_id.clone()),
            auth: auth.clone(),
            recover_from: None,
            verification: None,
            finalizing: None,
            recover_journal: false,
            stored_attempt: None,
            disk_failure: None,
            auth_failure: None,
            url_lost: false,
            disk_check_at: None,
            pending: None,
            removed_at_ms: None,
            finished_at_ms: None,
            queue_id,
            priority: Priority::Normal,
            queue_position,
            category: Some(category),
            name_confirmed,
            notify_decided: false,
            speed_limit,
        };
        // Durable before anything starts and before the acknowledgement: a lost acknowledgement
        // followed by a service restart still finds this job by its key.
        if let Some(store) = state.store.as_mut() {
            let record = IdempotencyRow {
                key: params.idempotency_key.clone(),
                fingerprint_sha256: fingerprint.clone(),
                job_id: job.id.clone(),
                created_at_ms: job.created_at_ms,
            };
            store
                .insert_job_with_speed_limit(&job.row(), Some(&record), speed_limit)
                .map_err(|e| {
                    eprintln!("dm-service: could not record a new job: {e}");
                    ServiceError::new(
                        ErrorKind::Internal,
                        "the download could not be recorded, so it was not started",
                    )
                    .with_action(NextAction::Retry)
                })?;
        }
        // CORE-08: outside its queue's window it waits with `schedule_window`.
        if let Some(rt) = state.schedules.get(&job.queue_id) {
            job.sync_schedule_hold(rt.eligible(self.now_ts()));
        }
        // Accepted and durable; it transfers as soon as an active-file slot is free (B1.5).
        job.queue(Pending::Fresh);
        let id = job.id.clone();
        state
            .idempotency
            .insert(params.idempotency_key, (fingerprint, id.clone()));
        state.jobs.push(job);
        // A job accepted into a stopped queue waits for Start queue (applied by admission).
        let State {
            jobs,
            store,
            queues,
            ..
        } = &mut *state;
        self.admit(jobs, queues, store).await;
        Ok(find_job(jobs, &id)?.snapshot())
    }

    /// Jobs in the list: everything except those removed from it.
    pub async fn list(&self) -> Vec<DownloadSnapshot> {
        self.state
            .lock()
            .await
            .jobs
            .iter()
            .filter(|j| j.removed_at_ms.is_none())
            .map(Job::snapshot)
            .collect()
    }

    /// "Remove from list" (B2.3, ADR 0013). Only a completed, failed or cancelled job with no
    /// transfer and no finalization is removed; anything unfinished is refused (cancel it first).
    /// A failed job may still own its terminal engine attempt: it is released here without
    /// deleting its partial output. The mark is persisted before the acknowledgement; the job row
    /// and its idempotency record stay, so `get` and a replay of the original add still answer
    /// with this job. No file is touched. Removing a removed job answers with it again.
    pub async fn remove(&self, id: &JobId) -> Result<DownloadSnapshot, ServiceError> {
        let mut guard = self.state.lock().await;
        let State { jobs, store, .. } = &mut *guard;
        let job = find_job(jobs, id)?;
        if job.removed_at_ms.is_some() {
            return Ok(job.snapshot());
        }
        if !job.phase.is_terminal() || job.finalizing.is_some() {
            return Err(ServiceError::new(
                ErrorKind::InvalidRequest,
                "only a completed, failed or cancelled download can be removed from the list",
            ));
        }
        self.tombstone(job, store).await?;
        Ok(job.snapshot())
    }

    /// The durable removal shared by `downloads.v1.remove` and history retention (ADR 0013,
    /// ADR 0018): releases a terminal attempt's handle (keeping every file), then records the
    /// tombstone. The caller checked that the job is terminal and not finalizing.
    async fn tombstone(
        &self,
        job: &mut Job,
        store: &mut Option<Store>,
    ) -> Result<(), ServiceError> {
        let id = job.id.clone();
        let id = &id;
        if let Some(attempt) = job.attempt.as_ref() {
            // A failed transfer is already terminal. Stop and forget its handle, but keep every
            // output file (unlike `discard`, which deletes the attempt's partial file).
            self.backend.remove(&attempt.handle).await.map_err(|_| {
                ServiceError::new(
                    ErrorKind::Internal,
                    "the download could not be released, so it stays in the list",
                )
                .with_action(NextAction::Retry)
            })?;
            job.attempt = None;
        }
        let at = now_ms();
        let at = match store.as_mut() {
            Some(s) => if finalize::fault::active("fail_remove_store") {
                // Debug builds only: the store refuses the write (process tests).
                Err(StorageError::Sql("injected failure".into()))
            } else {
                s.remove_job(id, at)
            }
            .map_err(|e| {
                eprintln!("dm-service: removal of job {id} not recorded: {e}");
                match e {
                    StorageError::NotRemovable => ServiceError::new(
                        ErrorKind::InvalidRequest,
                        "only a completed, failed or cancelled download can be removed from the list",
                    ),
                    _ => ServiceError::new(
                        ErrorKind::Internal,
                        "the removal could not be recorded, so the download stays in the list",
                    )
                    .with_action(NextAction::Retry),
                }
            })?,
            None => at,
        };
        job.removed_at_ms = Some(at);
        Ok(())
    }

    // ------------------------------------------------------------ history retention (B2.12)

    /// `history.v1.get`.
    pub async fn history_settings(&self) -> HistorySettings {
        HistorySettings {
            retention_days: self.state.lock().await.retention_days,
        }
    }

    /// `history.v1.set`: saved before it is acknowledged; the next sweep applies it.
    pub async fn set_history(
        &self,
        settings: HistorySettings,
    ) -> Result<HistorySettings, ServiceError> {
        check_retention(settings.retention_days)?;
        let mut state = self.state.lock().await;
        if let Some(store) = state.store.as_mut() {
            store.save_retention(settings.retention_days).map_err(|e| {
                eprintln!("dm-service: history retention not recorded: {e}");
                ServiceError::new(
                    ErrorKind::Internal,
                    "the history setting could not be saved",
                )
                .with_action(NextAction::Retry)
            })?;
        }
        state.retention_days = settings.retention_days;
        Ok(settings)
    }

    /// `history.v1.preview`: what `retention_days` would remove now, without changing anything.
    pub async fn preview_history(
        &self,
        retention_days: Option<u32>,
    ) -> Result<HistoryPreview, ServiceError> {
        check_retention(retention_days)?;
        let now = now_ms();
        let state = self.state.lock().await;
        let listed = state
            .jobs
            .iter()
            .filter(|j| j.removed_at_ms.is_none() && j.phase.is_terminal());
        let (mut finished, mut expiring) = (0u32, 0u32);
        for job in listed {
            finished = finished.saturating_add(1);
            // A job that finished in this run counts as finished now (as the sweep would).
            let at = job.finished_at_ms.unwrap_or(now);
            if job.finalizing.is_none() && retention_due(at, retention_days, now) {
                expiring = expiring.saturating_add(1);
            }
        }
        Ok(HistoryPreview { expiring, finished })
    }

    /// `history.v1.clean`: applies the saved policy now, in batches, until nothing more is due
    /// (or every remaining due job failed to be recorded in this call).
    pub async fn clean_history(&self) -> HistoryCleanResult {
        let mut total = HistoryCleanResult::default();
        loop {
            let batch = self.sweep_history(RETENTION_BATCH).await;
            total.removed = total.removed.saturating_add(batch.removed);
            total.kept = batch.kept;
            if batch.removed == 0 || batch.removed < RETENTION_BATCH_U32 {
                return total;
            }
        }
    }

    /// One bounded retention sweep (startup, every [`RETENTION_SWEEP_INTERVAL`] and
    /// `history.v1.clean`). Removes at most `limit` due jobs, oldest first, through the durable
    /// removal; a job whose removal cannot be recorded stays listed and is retried next time.
    /// Never touches files, never discards backend output, never opens anything.
    pub async fn sweep_history(&self, limit: usize) -> HistoryCleanResult {
        self.sweep_history_at(now_ms(), limit).await
    }

    async fn sweep_history_at(&self, now: u64, limit: usize) -> HistoryCleanResult {
        let mut guard = self.state.lock().await;
        let state = &mut *guard;
        let days = state.retention_days;
        // Jobs that finished in this run get their (memory) finish time on first sight.
        for job in state.jobs.iter_mut() {
            if job.phase.is_terminal() && job.finished_at_ms.is_none() {
                job.finished_at_ms = Some(now);
            }
        }
        let mut due: Vec<(u64, usize)> = state
            .jobs
            .iter()
            .enumerate()
            .filter(|(_, j)| {
                j.removed_at_ms.is_none()
                    && j.phase.is_terminal()
                    && j.finalizing.is_none()
                    && j.finished_at_ms
                        .is_some_and(|at| retention_due(at, days, now))
            })
            .map(|(i, j)| (j.finished_at_ms.unwrap_or(now), i))
            .collect();
        due.sort();
        let mut result = HistoryCleanResult::default();
        let State { jobs, store, .. } = state;
        for (_, i) in due.into_iter().take(limit) {
            let Some(job) = jobs.get_mut(i) else {
                continue;
            };
            match self.tombstone(job, store).await {
                Ok(()) => result.removed = result.removed.saturating_add(1),
                Err(e) => {
                    eprintln!(
                        "dm-service: history retention kept job {}: {}",
                        job.id,
                        e.0.kind.wire_name()
                    );
                    result.kept = result.kept.saturating_add(1);
                }
            }
        }
        if result.removed > 0 {
            trace_stream(
                "history_swept",
                usize::try_from(result.removed).unwrap_or(usize::MAX),
            );
            // Open clients learn about the removals at once (job_removed events).
            guard.publish();
        }
        result
    }

    pub async fn get(&self, id: &JobId) -> Result<DownloadSnapshot, ServiceError> {
        Ok(self.state.lock().await.job_mut(id)?.snapshot())
    }

    pub async fn pause(&self, id: &JobId) -> Result<DownloadSnapshot, ServiceError> {
        let mut guard = self.state.lock().await;
        let State {
            jobs,
            store,
            queues,
            ..
        } = &mut *guard;
        let job = find_job(jobs, id)?;
        ensure_not_terminal(job)?;
        if job.desired_state != DesiredState::Paused {
            if let Some(attempt) = &job.attempt {
                self.backend.pause(&attempt.handle).await?;
                // The backend confirms (flushes) bytes when it pauses; report that, not the last
                // poll, so the acknowledgement matches the partial file.
                if let Ok(confirmed) = self.backend.progress(&attempt.handle).await {
                    job.downloaded = confirmed.completed;
                }
            }
            job.desired_state = DesiredState::Paused;
            // A pause ends a schedule exemption (CORE-08): the paused job is held like any other
            // outside its window, so resuming it waits for the window.
            if job.schedule_exempt {
                job.schedule_exempt = false;
                job.sync_schedule_hold(false);
            }
            // The paused state and the checkpoint of the bytes the backend just synced are
            // committed together; without a new checkpoint only the job row is written.
            if !self.take_checkpoint(store, job).await {
                persist(store, job);
            }
        }
        let snapshot = job.snapshot();
        // A paused job frees its slot for the next pending one.
        self.admit(jobs, queues, store).await;
        Ok(snapshot)
    }

    pub async fn resume(&self, id: &JobId) -> Result<DownloadSnapshot, ServiceError> {
        let mut guard = self.state.lock().await;
        if self.is_stopping() {
            return Err(stopping());
        }
        // ADR 0030: nothing new starts while an update is being prepared.
        self.refuse_while_updating()?;
        let State {
            jobs,
            store,
            queues,
            ..
        } = &mut *guard;
        let active = jobs.iter().filter(|j| j.is_active()).count();
        let queue_of = find_job(jobs, id)?.queue_id.clone();
        let queue_active = jobs
            .iter()
            .filter(|j| j.queue_id == queue_of && j.is_active())
            .count();
        let queue = queues.iter().find(|q| q.queue_id == queue_of);
        // Resuming now is possible only with a global slot, a slot of the job's queue, and a
        // running queue; otherwise the job waits for admission (a stopped queue keeps its hold).
        let can_start_now = active < self.active_limit()
            && queue.is_none_or(|q| {
                q.running && queue_active < usize::try_from(q.max_active).unwrap_or(usize::MAX)
            });
        let job = find_job(jobs, id)?;
        // A queue hold (its schedule window, CORE-08) keeps a resumed job waiting for admission.
        let can_start_now = can_start_now && !job.blockers.iter().any(|b| is_queue_policy(*b));
        ensure_not_terminal(job)?;
        if job.desired_state == DesiredState::Running {
            return Ok(job.snapshot());
        }
        if job.is_sign_in_held() {
            // ADR 0028: it continues once reconnected from the browser; the wish is kept.
            job.desired_state = DesiredState::Running;
            persist(store, job);
            return Ok(job.snapshot());
        }
        if job.is_disk_blocked() {
            // Still waiting for space: the poll loop continues it once the budget fits.
            job.desired_state = DesiredState::Running;
            job.disk_check_at = None;
            persist(store, job);
            return Ok(job.snapshot());
        }
        // Gate on the engine's current byte count: the last poll can predate the pause.
        if let Some(attempt) = &job.attempt {
            let fresh = self.backend.progress(&attempt.handle).await?;
            job.downloaded = job.downloaded.max(fresh.completed);
        }
        if job.downloaded.0 > 0
            && support_of(&self.capabilities, Capability::ResumeStrongValidator)
                != CapabilitySupport::Supported
        {
            return Err(ServiceError::new(
                ErrorKind::BackendCapabilityUnavailable,
                "resuming partial data needs strong-validator resume, which this backend does not support",
            )
            .with_action(NextAction::ChooseRestartOrKeep));
        }
        match &job.attempt {
            // A slot is free: resume now, so a refusal (e.g. no strong validator) reaches the
            // caller and the job stays paused, exactly as before admission existed.
            Some(attempt) if can_start_now && !job.is_name_held() => {
                self.backend
                    .resume(&attempt.handle)
                    .await
                    .map_err(resume_refusal)?;
                job.pending = None;
                job.blockers.retain(|b| *b != Blocker::QueueLimit);
            }
            Some(_) => job.queue(Pending::Resume),
            // A scheduled retry keeps its cool-down; the poller queues it when due.
            None if job.retry_at.is_some() => {}
            None => job.queue(Pending::Fresh),
        }
        job.desired_state = DesiredState::Running;
        let id = job.id.clone();
        persist(store, job);
        self.admit(jobs, queues, store).await;
        Ok(find_job(jobs, &id)?.snapshot())
    }

    /// Cancels a job. Acknowledged only after the backend has removed the transfer and the attempt
    /// has been invalidated.
    pub async fn cancel(&self, id: &JobId) -> Result<DownloadSnapshot, ServiceError> {
        let mut guard = self.state.lock().await;
        let State {
            jobs,
            store,
            queues,
            ..
        } = &mut *guard;
        let job = find_job(jobs, id)?;
        match job.phase {
            Phase::Cancelled => return Ok(job.snapshot()),
            Phase::Completed => {
                return Err(ServiceError::new(
                    ErrorKind::InvalidRequest,
                    "job already completed",
                ));
            }
            _ => {}
        }
        let scanning = job
            .finalizing
            .as_ref()
            .is_some_and(|e| e.stage == JournalStage::Placed && e.scan_started_ms.is_some());
        if !scanning
            && job
                .finalizing
                .as_ref()
                .is_some_and(|e| e.stage >= JournalStage::Placed)
        {
            return Err(ServiceError::new(
                ErrorKind::InvalidRequest,
                "the download is already at its destination and is being completed",
            ));
        }
        if scanning {
            // F07 (ADR 0026): the OS check cannot be interrupted; its ticket is revoked so a late
            // result can never complete this job. The placed file stays, unchecked, and says so;
            // our own staging name of it goes.
            self.scans.revoke(&job.id);
            if let Some(entry) = job.finalizing.as_ref()
                && entry.placement == dm_storage::Placement::Staged
                && entry.staging_path != entry.final_path
            {
                let _ = std::fs::remove_file(&entry.staging_path);
            }
            job.scan = Some(dm_domain::api::ScanRecord {
                status: dm_domain::api::ScanStatus::Skipped,
                reason: Some(dm_domain::api::ScanReason::Cancelled),
                origin_marking: None,
            });
            if let Some(attempt) = job.attempt.take() {
                let _ = self.backend.remove(&attempt.handle).await;
            }
            job.finalizing = None;
            job.stored_attempt = None;
            job.pending = None;
            job.desired_state = DesiredState::Cancelled;
            job.phase = Phase::Cancelled;
            job.retry_at = None;
            job.blockers.clear();
            if let Some(s) = store.as_mut()
                && let Err(e) = s.abandon_finalization(&job.row())
            {
                eprintln!(
                    "dm-service: cancellation of job {} not recorded: {e}",
                    job.id
                );
            }
            trace("scan_cancelled", &job.id, None, 0);
            let snapshot = job.snapshot();
            self.admit(jobs, queues, store).await;
            return Ok(snapshot);
        }
        // Ownership ends only after the engine confirmed the transfer stopped and its writes ended;
        // if stopping fails, the job keeps its attempt and the error reaches the caller.
        if let Some(attempt) = job.attempt.as_ref() {
            self.backend.remove(&attempt.handle).await?;
        }
        job.attempt = None;
        // A finalization that had not placed anything is abandoned with the job (the store drops
        // its entry in the same transaction).
        job.finalizing = None;
        job.stored_attempt = None;
        job.pending = None;
        job.desired_state = DesiredState::Cancelled;
        job.phase = Phase::Cancelled;
        job.retry_at = None;
        job.blockers.clear();
        persist(store, job);
        let snapshot = job.snapshot();
        self.admit(jobs, queues, store).await;
        Ok(snapshot)
    }

    /// Polls the backend once for every running attempt and applies the results.
    pub async fn poll_once(&self) {
        self.expire_update().await;
        self.end_finished_contexts().await;
        let mut guard = self.state.lock().await;
        // Schedules first: a window that just closed or opened applies before this poll admits.
        self.evaluate_schedules(&mut guard, false).await;
        let State {
            jobs,
            store,
            queues,
            ..
        } = &mut *guard;
        let now = tokio::time::Instant::now();
        for i in 0..jobs.len() {
            // The final name is chosen as soon as response metadata is seen, and before any
            // finalization of the same poll (B1.6).
            select_final_name(jobs, i, store, self.ask());
            let Some(job) = jobs.get_mut(i) else {
                break;
            };
            if job.phase.is_terminal() || job.desired_state != DesiredState::Running {
                continue;
            }
            let before = job.checkpoint_key();
            if matches!(job.phase, Phase::Verifying | Phase::Scanning) {
                if job.is_name_held() {
                    // Waits for downloads.v1.confirm_name (or cancel); nothing else to do.
                    continue;
                }
                if job.is_disk_blocked() {
                    // Finalization waits for space at its `verified` stage.
                    if job.disk_check_at.is_some_and(|at| at > now) {
                        continue;
                    }
                    job.blockers.clear();
                    job.error = None;
                    if let Some(entry) = job.finalizing.clone() {
                        self.run_finalization(store, job, entry, true).await;
                        continue;
                    }
                }
                // The transfer is complete: finalize through the journal, which writes the job
                // row itself at every stage.
                self.finalize(store, job).await;
                continue;
            }
            if job.is_disk_blocked() && job.attempt.is_none() {
                self.recheck_disk(store, job, now).await;
                continue;
            }
            self.poll_job(job, now).await;
            select_final_name(jobs, i, store, self.ask());
            let Some(job) = jobs.get_mut(i) else {
                break;
            };
            if let Some(e) = job.disk_failure.take() {
                self.block_on_disk(store, job, e, now).await;
                continue;
            }
            if job.auth_failure.take().is_some() {
                self.expire_context(store, job);
                let error = self.sign_in_error(job);
                self.hold_for_sign_in(store, job, error).await;
                continue;
            }
            if matches!(job.phase, Phase::Verifying | Phase::Scanning) {
                self.finalize(store, job).await;
                continue;
            }
            if job.checkpoint_key() != before {
                persist(store, job);
            }
            let due = job
                .checkpointed_at
                .is_none_or(|at| now.saturating_duration_since(at) >= CHECKPOINT_INTERVAL);
            if due && !job.phase.is_terminal() && job.attempt.is_some() {
                job.checkpointed_at = Some(now);
                self.take_checkpoint(store, job).await;
            }
        }
        // Slots freed by completions, failures or pauses go to pending jobs (B2.11 order).
        self.admit(jobs, queues, store).await;
        // CORE-09: decisions for outcomes made durable in this poll (or by a command since).
        let notices = decide_notifications(&mut guard);
        // Progress and changes of this poll, coalesced to one publication (B2.9).
        guard.publish();
        drop(guard);
        self.dispatch(notices);
    }

