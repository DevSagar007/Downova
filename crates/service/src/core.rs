//! Job coordinator (B0.2; durable jobs and idempotency since B1.1).
//!
//! **Persistence (B1.1, ADR 0006).** With a [`Store`] attached ([`Core::with_store`]):
//! - a job and its idempotency record are written in one transaction *before*
//!   `downloads.v1.add` is acknowledged;
//! - every later state change (pause, resume, cancel, failure, completion) is written as it
//!   happens; byte progress is not written per packet.
//!
//! After a restart the same key returns the same job, and a different payload still conflicts
//! (COR-09). Without a store (unit tests) the coordinator keeps everything in memory, as in B0.
//!
//! **Durable checkpoints and recovery (B1.2, ADR 0007).** The backend's opaque checkpoint of the
//! current attempt is committed together with the job row (refused for a stale attempt):
//! - when a job is paused;
//! - at most every [`CHECKPOINT_INTERVAL`] while it transfers, when the confirmed bytes grew;
//! - for every running job during a graceful shutdown ([`Core::prepare_shutdown`]).
//!
//! On start, [`Core::recover`] gives each unfinished job that has a checkpoint a **new** attempt,
//! restores it through the backend (which re-verifies the data on disk), moves the checkpoint to
//! the new attempt in one transaction, and resumes it only if the user had not paused it. An
//! unfinished job without a usable checkpoint, or whose restore is refused, fails with an
//! explicit reason. Cancelled and completed jobs never restart.
//!
//! **Completion journal (B1.3, ADR 0008).** A transfer the backend reports complete is finalized
//! through the journal in [`finalize`]: intent → verified (length, SHA-256, trusted checksum) →
//! placed (never over an existing file) → complete (job `completed` with its verification
//! evidence). Unfinished entries are reconciled at startup before checkpoint recovery.
//!
//! **Disk budget (B1.4, ADR 0009).** A transfer the backend stops with `DISK_FULL` or
//! `VOLUME_MISSING` is not failed: its last durable checkpoint is committed, the attempt is released
//! (its partial file kept), and the job waits with the `disk_unavailable` / `volume_missing`
//! blocker, keeping its desired state. Every [`DISK_RECHECK_INTERVAL`] the budget is checked again;
//! once it fits, the job continues through the validated restore path (or, with nothing confirmed
//! yet, starts again). Finalization that cannot copy for lack of space waits the same way at its
//! `verified` stage, with its journal entry kept.
//!
//! **Admission (ADR 0010, amended by ADR 0023).** The saved global limit (default
//! [`MAX_ACTIVE_FILES`]) and each queue's limit control active jobs. A job that
//! is ready to transfer (new, resumed by the user, recovered after a restart, due after a retry
//! cool-down, or cleared by the disk policy) is marked pending and shown `queued` with the
//! `queue_limit` blocker; [`Core::admit`] starts pending jobs, oldest first, while slots are free.
//! Admission never waits: it counts and starts, so RPCs stay responsive. Only a job with a live
//! attempt that the user wants running and that is not finalizing, waiting for disk or cooling
//! down occupies a slot. Per-host connection limits are enforced inside the backend.
//!
//! **Duplicates, destinations and names (B2.8, ADR 0015).** `downloads.v1.check` lists unremoved
//! jobs with the same link identity ([`dm_domain::policy::link_identity`]: exact URL, scheme and
//! host case-folded). `add` with `on_duplicate: refuse` re-checks under the coordinator lock, so
//! two concurrent submissions of one link cannot both pass; an idempotent replay (same key) is
//! answered before any duplicate check. The destination folder is resolved once, at acceptance,
//! from the category's rule (or the profile folder) and stored with the job; later rule edits
//! never move a job, its partial file, checkpoint or journal entry. With the `ask` collision
//! policy a job whose final name had to be changed waits before placement with the
//! `name_conflict` blocker until `downloads.v1.confirm_name` (or cancel); nothing is ever
//! overwritten under either policy, and a name taken between selection and placement is replaced
//! by the next free one (re-journaled before placing).
//!
//! **Queues and priority (B2.11, ADR 0017).** Every job belongs to a persistent queue (default
//! `main`) with a manual position and a priority. Admission orders ready jobs by
//! [`dm_domain::policy::admission_order`] and starts them while both the global slots and the
//! queue's own `max_active` allow. A stopped queue holds its jobs with `queue_stopped` (its
//! transfers are paused and checkpointed, `desired_state` untouched); starting it never overrides
//! a user pause, a cancellation, a disk hold or a retry cool-down. Lowering a limit never
//! preempts a running transfer; it only delays new starts.
//!
//! Rules enforced here:
//! - Job IDs (`job_…`) and attempt IDs (`att_…`) are generated by the service; backend handles are
//!   opaque and never leave this module.
//! - Every job start is gated on the backend capability report; anything not `Supported` is
//!   refused with `BACKEND_CAPABILITY_UNAVAILABLE` (no silent fallback).
//! - Resuming a transfer that already holds partial bytes needs `ResumeStrongValidator`; while the
//!   backend reports it unsupported, resume is refused with `choose_restart_or_keep`.
//! - Progress is applied only for the job's *current* attempt and never to a terminal job, so a
//!   late engine event cannot revive a cancelled job (ADV06 cancellation guard).
//! - Automatic retries are owned here, not by the engine (COR-04, B0.4.1): a transient failure
//!   (`NETWORK_OFFLINE`, `SERVER_BUSY`) schedules a fresh attempt after the server's
//!   `Retry-After` or a bounded, jittered backoff ([`dm_domain::retry`]). The failed attempt's
//!   partial output is discarded first, so the new attempt starts from zero rather than resuming
//!   without a validator. 429/503 cool-downs show the `rate_limit_cooldown` blocker.

