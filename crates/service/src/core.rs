/// Error returned to clients; always sanitized (no raw URLs, headers or engine messages).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ServiceError(pub ErrorData);

impl ServiceError {
    pub fn new(kind: ErrorKind, detail: impl Into<String>) -> Self {
        Self(kind.to_error_data(detail))
    }

    fn with_action(mut self, action: NextAction) -> Self {
        self.0.next_action = action;
        self
    }
}

impl From<dm_backend_api::BackendError> for ServiceError {
    fn from(e: dm_backend_api::BackendError) -> Self {
        Self::new(e.kind, e.detail)
    }
}

#[derive(Debug)]
struct Attempt {
    id: AttemptId,
    handle: BackendHandle,
}

#[derive(Debug)]
struct Job {
    id: JobId,
    /// Raw URL (may hold signed-query secrets). Never serialized; snapshots use `redact_url`.
    url: String,
    display_name: String,
    destination: PathBuf,
    desired_state: DesiredState,
    phase: Phase,
    downloaded: ByteCount,
    total: Option<ByteCount>,
    expected_sha256: Option<String>,
    attempt: Option<Attempt>,
    error: Option<ErrorData>,
    /// Automatic retries already scheduled for this job.
    retries: u32,
    /// When the next automatic attempt may start (no attempt exists meanwhile).
    retry_at: Option<tokio::time::Instant>,
    blockers: Vec<Blocker>,
    created_at_ms: u64,
}

impl Job {
    fn row(&self) -> JobRow {
        JobRow {
            id: self.id.clone(),
            url: self.url.clone(),
            display_name: self.display_name.clone(),
            destination: self.destination.clone(),
            desired_state: self.desired_state,
            phase: self.phase,
            downloaded: self.downloaded,
            total: self.total,
            expected_sha256: self.expected_sha256.clone(),
            error: self.error.clone(),
            created_at_ms: self.created_at_ms,
            updated_at_ms: now_ms(),
        }
    }

    /// Rebuilds a job from its stored row. A job that was still running when the service stopped
    /// cannot continue yet: its engine checkpoint was not persisted (B1.2).
    fn restore(row: JobRow) -> (Self, bool) {
        let mut job = Self {
            id: row.id,
            url: row.url,
            display_name: row.display_name,
            destination: row.destination,
            desired_state: row.desired_state,
            phase: row.phase,
            downloaded: row.downloaded,
            total: row.total,
            expected_sha256: row.expected_sha256,
            attempt: None,
            error: row.error,
            retries: 0,
            retry_at: None,
            blockers: Vec::new(),
            created_at_ms: row.created_at_ms,
        };
        let interrupted = !job.phase.is_terminal();
        if interrupted {
            job.fail(ErrorData {
                kind: ErrorKind::ServiceUnavailable,
                retryable: false,
                next_action: NextAction::None,
                detail: Some(INTERRUPTED.to_owned()),
            });
        }
        (job, interrupted)
    }

    /// What a durable write must capture; a changed byte count alone does not trigger one.
    fn checkpoint_key(&self) -> (Phase, DesiredState, Option<ErrorKind>, Option<ByteCount>) {
        (
            self.phase,
            self.desired_state,
            self.error.as_ref().map(|e| e.kind),
            self.total,
        )
    }
    fn snapshot(&self) -> DownloadSnapshot {
        DownloadSnapshot {
            job_id: self.id.clone(),
            attempt_id: self.attempt.as_ref().map(|a| a.id.clone()),
            display_name: self.display_name.clone(),
            source_display: redact_url(&self.url),
            desired_state: self.desired_state,
            phase: self.phase,
            blockers: self.blockers.clone(),
            downloaded_bytes: self.downloaded,
            total_bytes: self.total,
            error: self.error.clone(),
        }
    }

    fn fail(&mut self, error: ErrorData) {
        self.phase = Phase::Failed;
        self.error = Some(error);
    }
}

/// Reason shown for a job that was unfinished when the service stopped.
pub const INTERRUPTED: &str = "the download was interrupted when the Downova service stopped; continuing after a restart is not supported yet, so add the link again";

/// Idempotency records older than this are pruned at startup (COR-09 bounded retention).
pub const IDEMPOTENCY_RETENTION_MS: u64 = 30 * 24 * 60 * 60 * 1000;

#[derive(Debug, Default)]
struct State {
    jobs: Vec<Job>,
    /// idempotency key → (SHA-256 of the request fingerprint, job). Mirrors the store.
    idempotency: HashMap<String, (String, JobId)>,
    /// Durable storage; `None` keeps everything in memory (unit tests).
    store: Option<Store>,
}

fn find_job<'a>(jobs: &'a mut [Job], id: &JobId) -> Result<&'a mut Job, ServiceError> {
    jobs.iter_mut()
        .find(|j| &j.id == id)
        .ok_or_else(|| ServiceError::new(ErrorKind::InvalidRequest, format!("unknown job {id}")))
}

impl State {
    fn job_mut(&mut self, id: &JobId) -> Result<&mut Job, ServiceError> {
        find_job(&mut self.jobs, id)
    }
}

/// Writes a job's state. A failed write is reported on stderr (never with the URL) and does not
/// undo the change in memory.
fn persist(store: &mut Option<Store>, job: &Job) {
    if let Some(store) = store
        && let Err(e) = store.update_job(&job.row())
    {
        eprintln!("dm-service: could not record job {}: {e}", job.id);
    }
}

fn now_ms() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_or(0, |d| u64::try_from(d.as_millis()).unwrap_or(u64::MAX))
}

/// Destination profiles: id → directory.
pub type Profiles = HashMap<String, PathBuf>;

/// The coordinator.
#[derive(Debug)]
pub struct Core<B> {
    backend: B,
    backend_version: Option<String>,
    capabilities: Vec<CapabilityReport>,
    profiles: Profiles,
    instance_id: String,
    retry_policy: RetryPolicy,
    state: Mutex<State>,
}

/// Connections requested per file when segmented transfer is permitted (research §15.4).
const SEGMENTED_CONNECTIONS: u8 = 4;

impl<B: DownloadBackend> Core<B> {
    pub fn new(backend: B, backend_version: Option<String>, profiles: Profiles) -> Self {
        let capabilities = backend.capabilities();
        Self {
            backend,
            backend_version,
            capabilities,
            profiles,
            instance_id: format!("svc_{}", random_hex(8)),
            retry_policy: RetryPolicy::default(),
            state: Mutex::new(State::default()),
        }
    }

    /// Attaches durable storage and restores what it holds: jobs (unfinished ones as interrupted)
    /// and idempotency records younger than [`IDEMPOTENCY_RETENTION_MS`].
    pub fn with_store(self, mut store: Store) -> Result<Self, StorageError> {
        store.prune_idempotency(now_ms().saturating_sub(IDEMPOTENCY_RETENTION_MS))?;
        let mut jobs = Vec::new();
        for row in store.load_jobs()? {
            let (job, interrupted) = Job::restore(row);
            if interrupted {
                store.update_job(&job.row())?;
            }
            jobs.push(job);
        }
        let idempotency = store
            .load_idempotency()?
            .into_iter()
            .map(|r| (r.key, (r.fingerprint_sha256, r.job_id)))
            .collect();
        {
            let mut state = self
                .state
                .try_lock()
                .map_err(|_| StorageError::Open("the coordinator is already in use".to_owned()))?;
            state.jobs = jobs;
            state.idempotency = idempotency;
            state.store = Some(store);
        }
        Ok(self)
    }

    /// Overrides the automatic retry policy (tests, future settings).
    pub fn with_retry_policy(mut self, policy: RetryPolicy) -> Self {
        self.retry_policy = policy;
        self
    }

    pub fn backend(&self) -> &B {
        &self.backend
    }

    pub fn hello(&self) -> HelloResult {
        hello_result(
            &self.backend,
            self.backend_version.clone(),
            &self.instance_id,
        )
    }

    pub async fn add(&self, params: AddDownloadParams) -> Result<DownloadSnapshot, ServiceError> {
        validate_idempotency_key(&params.idempotency_key)?;
        let fingerprint = fingerprint_sha256(&params);
        let mut state = self.state.lock().await;

        if let Some((existing_fp, job_id)) = state.idempotency.get(&params.idempotency_key) {
            if *existing_fp != fingerprint {
                return Err(ServiceError::new(
                    ErrorKind::IdempotencyConflict,
                    "idempotency key was already used for a different request",
                ));
            }
            let job_id = job_id.clone();
            return Ok(state.job_mut(&job_id)?.snapshot());
        }

        let scheme = url_scheme(&params.source.url)?;
        let required = if scheme == "https" {
            Capability::Https
        } else {
            Capability::Http
        };
        // Input validation first, so a malformed request is reported as such even while the
        // capability is unavailable.
        let dir = self
            .profiles
            .get(&params.destination_profile_id)
            .ok_or_else(|| {
                ServiceError::new(ErrorKind::InvalidRequest, "unknown destination profile")
            })?;
        if let Some(sha) = &params.expected_sha256
            && (sha.len() != 64 || !sha.bytes().all(|b| b.is_ascii_hexdigit()))
        {
            return Err(ServiceError::new(
                ErrorKind::InvalidRequest,
                "expected_sha256 must be 64 hex digits",
            ));
        }
        // Gate before creating anything: a refused request leaves no job and no idempotency
        // record, so the same key can succeed once the capability is promoted.
        require_capability(&self.capabilities, required)?;

        let taken: Vec<String> = state
            .jobs
            .iter()
            .filter(|j| &j.destination == dir)
            .map(|j| j.display_name.clone())
            .collect();
        let display_name = unique_file_name(dir, &file_name_from_url(&params.source.url), &taken);
        let mut job = Job {
            id: new_job_id(),
            url: params.source.url.clone(),
            display_name,
            destination: dir.clone(),
            desired_state: DesiredState::Running,
            phase: Phase::Queued,
            downloaded: ByteCount(0),
            total: params.expected_size_bytes,
            expected_sha256: params.expected_sha256.map(|s| s.to_ascii_lowercase()),
            attempt: None,
            error: None,
            retries: 0,
            retry_at: None,
            blockers: Vec::new(),
            created_at_ms: now_ms(),
        };
        // Durable before anything starts and before the acknowledgement: a lost acknowledgement
        // followed by a service restart still finds this job by its key.
        if let Some(store) = state.store.as_mut() {
            let record = IdempotencyRow {
                key: params.idempotency_key.clone(),
                fingerprint_sha256: fingerprint.clone(),
                job_id: job.id.clone(),
                created_at_ms: job.created_at_ms,
            };
            store.insert_job(&job.row(), Some(&record)).map_err(|e| {
                eprintln!("dm-service: could not record a new job: {e}");
                ServiceError::new(
                    ErrorKind::Internal,
                    "the download could not be recorded, so it was not started",
                )
                .with_action(NextAction::Retry)
            })?;
        }
        if let Err(e) = self.start_attempt(&mut job).await {
            job.fail(e.0);
            persist(&mut state.store, &job);
        }
        let snapshot = job.snapshot();
        state
            .idempotency
            .insert(params.idempotency_key, (fingerprint, job.id.clone()));
        state.jobs.push(job);
        Ok(snapshot)
    }

    pub async fn list(&self) -> Vec<DownloadSnapshot> {
        self.state
            .lock()
            .await
            .jobs
            .iter()
            .map(Job::snapshot)
            .collect()
    }

    pub async fn get(&self, id: &JobId) -> Result<DownloadSnapshot, ServiceError> {
        Ok(self.state.lock().await.job_mut(id)?.snapshot())
    }

    pub async fn pause(&self, id: &JobId) -> Result<DownloadSnapshot, ServiceError> {
        let mut guard = self.state.lock().await;
        let State { jobs, store, .. } = &mut *guard;
        let job = find_job(jobs, id)?;
        ensure_not_terminal(job)?;
        if job.desired_state != DesiredState::Paused {
            if let Some(attempt) = &job.attempt {
                self.backend.pause(&attempt.handle).await?;
                // The backend confirms (flushes) bytes when it pauses; report that, not the last
                // poll, so the acknowledgement matches the partial file.
                if let Ok(confirmed) = self.backend.progress(&attempt.handle).await {
                    job.downloaded = confirmed.completed;
                }
            }
            job.desired_state = DesiredState::Paused;
            persist(store, job);
        }
        Ok(job.snapshot())
    }

    pub async fn resume(&self, id: &JobId) -> Result<DownloadSnapshot, ServiceError> {
        let mut guard = self.state.lock().await;
        let State { jobs, store, .. } = &mut *guard;
        let job = find_job(jobs, id)?;
        ensure_not_terminal(job)?;
        if job.desired_state == DesiredState::Running {
            return Ok(job.snapshot());
        }
        // Gate on the engine's current byte count: the last poll can predate the pause.
        if let Some(attempt) = &job.attempt {
            let fresh = self.backend.progress(&attempt.handle).await?;
            job.downloaded = job.downloaded.max(fresh.completed);
        }
        if job.downloaded.0 > 0
            && support_of(&self.capabilities, Capability::ResumeStrongValidator)
                != CapabilitySupport::Supported
        {
            return Err(ServiceError::new(
                ErrorKind::BackendCapabilityUnavailable,
                "resuming partial data needs strong-validator resume, which this backend does not support",
            )
            .with_action(NextAction::ChooseRestartOrKeep));
        }
        match &job.attempt {
            Some(attempt) => self.backend.resume(&attempt.handle).await?,
            // A scheduled retry keeps its cool-down; the poller starts it when due.
            None if job.retry_at.is_some() => {}
            None => self.start_attempt(job).await?,
        }
        job.desired_state = DesiredState::Running;
        persist(store, job);
        Ok(job.snapshot())
    }

    /// Cancels a job. Acknowledged only after the backend has removed the transfer and the attempt
    /// has been invalidated.
    pub async fn cancel(&self, id: &JobId) -> Result<DownloadSnapshot, ServiceError> {
        let mut guard = self.state.lock().await;
        let State { jobs, store, .. } = &mut *guard;
        let job = find_job(jobs, id)?;
        match job.phase {
            Phase::Cancelled => return Ok(job.snapshot()),
            Phase::Completed => {
                return Err(ServiceError::new(
                    ErrorKind::InvalidRequest,
                    "job already completed",
                ));
            }
            _ => {}
        }
        if let Some(attempt) = job.attempt.take() {
            self.backend.remove(&attempt.handle).await?;
        }
        job.desired_state = DesiredState::Cancelled;
        job.phase = Phase::Cancelled;
        job.retry_at = None;
        job.blockers.clear();
        persist(store, job);
        Ok(job.snapshot())
    }

    /// Polls the backend once for every running attempt and applies the results.
    pub async fn poll_once(&self) {
        let mut guard = self.state.lock().await;
        let State { jobs, store, .. } = &mut *guard;
        let now = tokio::time::Instant::now();
        for job in jobs.iter_mut() {
            if job.phase.is_terminal() || job.desired_state != DesiredState::Running {
                continue;
            }
            let before = job.checkpoint_key();
            self.poll_job(job, now).await;
            if job.checkpoint_key() != before {
                persist(store, job);
            }
        }
    }

    async fn poll_job(&self, job: &mut Job, now: tokio::time::Instant) {
        let Some(attempt) = &job.attempt else {
            if job.retry_at.is_some_and(|at| at <= now) {
                job.retry_at = None;
                job.blockers.clear();
                if let Err(e) = self.start_attempt(job).await {
                    job.fail(e.0);
                }
            }
            return;
        };
        let (attempt_id, handle) = (attempt.id.clone(), attempt.handle.clone());
        match self.backend.progress(&handle).await {
            Ok(BackendProgress {
                state: TransferState::Failed(e),
                ..
            }) => self.after_failure(job, e, now).await,
            Ok(progress) => apply_progress(job, &attempt_id, progress).await,
            Err(e) => job.fail(ServiceError::from(e).0),
        }
    }

    /// A failed attempt either schedules a fresh one (transient kinds, within the policy) or
    /// fails the job.
    async fn after_failure(&self, job: &mut Job, e: BackendError, now: tokio::time::Instant) {
        let decision = decide_retry(
            &self.retry_policy,
            e.kind,
            job.retries,
            e.retry_after,
            jitter_sample(),
        );
        let busy = e.kind == ErrorKind::ServerBusy;
        let error = ServiceError::from(e).0;
        let RetryDecision::RetryAfter(delay) = decision else {
            job.fail(error);
            return;
        };
        if let Some(attempt) = &job.attempt
            && self.backend.discard(&attempt.handle).await.is_err()
        {
            // Without discarding, a new attempt could resume the partial without a validator.
            job.fail(error);
            return;
        }
        job.attempt = None;
        job.retries = job.retries.saturating_add(1);
        job.downloaded = ByteCount(0);
        job.phase = Phase::Queued;
        job.error = Some(error);
        job.retry_at = Some(now.checked_add(delay).unwrap_or(now));
        job.blockers = if busy {
            vec![Blocker::RateLimitCooldown]
        } else {
            Vec::new()
        };
    }

    /// Test hook: deliver a (possibly late) progress event for a specific attempt.
    #[cfg(test)]
    pub(crate) async fn deliver(&self, id: &JobId, attempt: &AttemptId, progress: BackendProgress) {
        let mut state = self.state.lock().await;
        if let Ok(job) = state.job_mut(id) {
            apply_progress(job, attempt, progress).await;
        }
    }

    async fn start_attempt(&self, job: &mut Job) -> Result<(), ServiceError> {
        let connections = match support_of(&self.capabilities, Capability::SegmentedHttp) {
            CapabilitySupport::Supported => SEGMENTED_CONNECTIONS,
            _ => 1,
        };
        let attempt_id = new_attempt_id();
        let handle = self
            .backend
            .start(TransferRequest {
                attempt_id: attempt_id.clone(),
                url: job.url.clone(),
                headers: Vec::new(),
                destination_dir: job.destination.clone(),
                file_name: job.display_name.clone(),
                max_connections: connections,
            })
            .await?;
        job.attempt = Some(Attempt {
            id: attempt_id,
            handle,
        });
        job.error = None;
        Ok(())
    }
}

/// Applies engine progress to a job, guarded by attempt identity and terminal state.
async fn apply_progress(job: &mut Job, attempt_id: &AttemptId, progress: BackendProgress) {
    let current = job.attempt.as_ref().map(|a| &a.id);
    if current != Some(attempt_id) || job.phase.is_terminal() {
        return; // stale attempt or late event after cancel/completion
    }
    job.downloaded = progress.completed;
    if progress.total.is_some() {
        job.total = progress.total;
    }
    match progress.state {
        TransferState::Waiting => job.phase = Phase::Queued,
        TransferState::Active => job.phase = Phase::Transferring,
        TransferState::Paused => {}
        TransferState::Removed => {
            job.fail(ErrorKind::Internal.to_error_data("transfer removed outside the service"));
        }
        TransferState::Failed(e) => job.fail(ServiceError::from(e).0),
        TransferState::Complete => {
            job.phase = Phase::Verifying;
            match verify(job).await {
                Ok(()) => job.phase = Phase::Completed,
                Err(e) => job.fail(e.0),
            }
        }
    }
}

/// Completion check: length (when known) and, if requested, the trusted SHA-256.
async fn verify(job: &Job) -> Result<(), ServiceError> {
    let path = job.destination.join(&job.display_name);
    if let Some(total) = job.total {
        let len = tokio::fs::metadata(&path)
            .await
            .map_err(|_| ServiceError::new(ErrorKind::Internal, "completed file is missing"))?
            .len();
        if len != total.0 {
            return Err(ServiceError::new(
                ErrorKind::InvalidRange,
                "completed file has the wrong length",
            ));
        }
    }
    if let Some(expected) = &job.expected_sha256 {
        let actual = sha256_file(&path).await?;
        if &actual != expected {
            return Err(ServiceError::new(
                ErrorKind::ChecksumMismatch,
                "SHA-256 does not match the expected value",
            ));
        }
    }
    Ok(())
}

async fn sha256_file(path: &Path) -> Result<String, ServiceError> {
    use sha2::{Digest, Sha256};
    let path = path.to_owned();
    tokio::task::spawn_blocking(move || {
        use std::io::Read;
        let mut file = std::fs::File::open(path)?;
        let mut hasher = Sha256::new();
        let mut buf = vec![0u8; 64 * 1024];
        loop {
            let n = file.read(&mut buf)?;
            if n == 0 {
                break;
            }
            hasher.update(buf.get(..n).unwrap_or_default());
        }
        Ok::<_, std::io::Error>(
            hasher
                .finalize()
                .iter()
                .map(|b| format!("{b:02x}"))
                .collect(),
        )
    })
    .await
    .map_err(|_| ServiceError::new(ErrorKind::Internal, "hash task failed"))?
    .map_err(|_| ServiceError::new(ErrorKind::Internal, "cannot read completed file"))
}

fn ensure_not_terminal(job: &Job) -> Result<(), ServiceError> {
    if job.phase.is_terminal() {
        return Err(ServiceError::new(
            ErrorKind::InvalidRequest,
            format!("job is {:?}", job.phase).to_lowercase(),
        ));
    }
    Ok(())
}

fn validate_idempotency_key(key: &str) -> Result<(), ServiceError> {
    let len_ok = (8..=128).contains(&key.len());
    if !len_ok || key.chars().any(char::is_control) {
        return Err(ServiceError::new(
            ErrorKind::InvalidRequest,
            "idempotency_key must be 8-128 printable characters",
        ));
    }
    Ok(())
}

/// SHA-256 of the canonical request fingerprint (same key + same fingerprint ⇒ same job). Only
/// the hash is kept, because the fingerprint contains the URL.
fn fingerprint_sha256(params: &AddDownloadParams) -> String {
    use sha2::{Digest, Sha256};
    let canonical = serde_json::json!([
        params.source.url,
        params.destination_profile_id,
        params.expected_size_bytes,
        params
            .expected_sha256
            .as_deref()
            .map(str::to_ascii_lowercase),
    ])
    .to_string();
    Sha256::digest(canonical.as_bytes())
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect()
}

/// Returns `http` / `https`, refusing everything else without echoing the URL.
fn url_scheme(url: &str) -> Result<&'static str, ServiceError> {
    let lower = url.get(..8).unwrap_or(url).to_ascii_lowercase();
    let (scheme, rest) = if lower.starts_with("https://") {
        ("https", &url[8..])
    } else if lower.starts_with("http://") {
        ("http", &url[7..])
    } else {
        return Err(ServiceError::new(
            ErrorKind::InvalidRequest,
            "only http:// and https:// URLs are supported",
        ));
    };
    let host = rest.split(['/', '?', '#']).next().unwrap_or_default();
    if host.is_empty() || url.chars().any(char::is_whitespace) {
        return Err(ServiceError::new(
            ErrorKind::InvalidRequest,
            "URL has no host or contains whitespace",
        ));
    }
    Ok(scheme)
}

/// Advisory file name from the URL path (the query is ignored: it may hold tokens).
fn file_name_from_url(url: &str) -> String {
    let without_query = url.split(['?', '#']).next().unwrap_or_default();
    let after_scheme = without_query
        .split_once("://")
        .map_or(without_query, |(_, r)| r);
    let last = after_scheme
        .split_once('/')
        .map_or("", |(_, p)| p)
        .rsplit('/')
        .next()
        .unwrap_or("");
    sanitize_file_name(&percent_decode(last))
}

fn percent_decode(input: &str) -> String {
    let bytes = input.as_bytes();
    let mut out = Vec::with_capacity(bytes.len());
    let mut i = 0usize;
    while let Some(&b) = bytes.get(i) {
        let decoded = (b == b'%')
            .then(|| bytes.get(i.saturating_add(1)..i.saturating_add(3)))
            .flatten()
            .and_then(|hex| std::str::from_utf8(hex).ok())
            .and_then(|hex| u8::from_str_radix(hex, 16).ok());
        match decoded {
            Some(value) => {
                out.push(value);
                i = i.saturating_add(3);
            }
            None => {
                out.push(b);
                i = i.saturating_add(1);
            }
        }
    }
    String::from_utf8_lossy(&out).into_owned()
}

/// Replaces separators, control and Windows-reserved characters; avoids reserved device names.
fn sanitize_file_name(name: &str) -> String {
    let cleaned: String = name
        .chars()
        .map(|c| {
            if c.is_control() || "<>:\"/\\|?*".contains(c) {
                '_'
            } else {
                c
            }
        })
        .collect();
    let trimmed = cleaned.trim().trim_end_matches('.').trim();
    let stem = trimmed.split('.').next().unwrap_or("").to_ascii_uppercase();
    const RESERVED: [&str; 22] = [
        "CON", "PRN", "AUX", "NUL", "COM1", "COM2", "COM3", "COM4", "COM5", "COM6", "COM7", "COM8",
        "COM9", "LPT1", "LPT2", "LPT3", "LPT4", "LPT5", "LPT6", "LPT7", "LPT8", "LPT9",
    ];
    if trimmed.is_empty() || trimmed == "." || trimmed == ".." {
        "download".to_owned()
    } else if RESERVED.contains(&stem.as_str()) {
        format!("_{trimmed}")
    } else {
        trimmed.chars().take(200).collect()
    }
}

/// Picks a name that exists neither on disk nor among this service's jobs: `a.zip`, `a (1).zip`, …
fn unique_file_name(dir: &Path, name: &str, taken: &[String]) -> String {
    let (stem, ext) = match name.rsplit_once('.') {
        Some((s, e)) if !s.is_empty() => (s.to_owned(), format!(".{e}")),
        _ => (name.to_owned(), String::new()),
    };
    let free = |candidate: &str| {
        !taken.iter().any(|t| t == candidate)
            && !dir.join(candidate).exists()
            && !dir.join(format!("{candidate}.aria2")).exists()
    };
    if free(name) {
        return name.to_owned();
    }
    (1u32..10_000)
        .map(|n| format!("{stem} ({n}){ext}"))
        .find(|c| free(c))
        .unwrap_or_else(|| format!("{stem} ({}){ext}", random_hex(4)))
}

/// Uniform sample in `0..=1000` for retry jitter.
fn jitter_sample() -> u16 {
    let mut buf = [0u8; 2];
    if getrandom::fill(&mut buf).is_err() {
        return 500;
    }
    u16::from_le_bytes(buf) % 1001
}

fn random_hex(bytes: usize) -> String {
    let mut buf = vec![0u8; bytes];
    // getrandom failing means the OS RNG is unavailable; fall back to time-derived uniqueness
    // (IDs need uniqueness, not secrecy).
    if getrandom::fill(&mut buf).is_err() {
        let nanos = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map_or(0, |d| d.as_nanos());
        buf = nanos
            .to_le_bytes()
            .iter()
            .copied()
            .cycle()
            .take(bytes)
            .collect();
    }
    buf.iter().map(|b| format!("{b:02x}")).collect()
}

fn new_job_id() -> JobId {
    JobId::parse(&format!("job_{}", random_hex(8))).unwrap_or_else(|_| unreachable!("valid id"))
}

fn new_attempt_id() -> AttemptId {
    AttemptId::parse(&format!("att_{}", random_hex(8))).unwrap_or_else(|_| unreachable!("valid id"))
}

