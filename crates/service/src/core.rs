/// Test/diagnostic hook: when `DOWNOVA_CHECKPOINT_TRACE` names a file, every committed checkpoint
/// and recovery outcome is appended to it as one JSON line (job, attempt, bytes; never URLs).
/// Process tests use it as a deterministic barrier because the database is locked by the service.
fn trace(event: &str, job: &JobId, attempt: Option<&AttemptId>, confirmed: u64) {
    let Some(path) = std::env::var_os("DOWNOVA_CHECKPOINT_TRACE") else {
        return;
    };
    let line = serde_json::json!({
        "event": event,
        "job_id": job.as_str(),
        "attempt_id": attempt.map(AttemptId::as_str),
        "confirmed": confirmed,
    });
    use std::io::Write;
    if let Ok(mut file) = std::fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(path)
    {
        let _ = writeln!(file, "{line}");
    }
}

