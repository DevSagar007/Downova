/// The policy blocker for a disk-related error kind, if it is one.
fn disk_blocker(kind: ErrorKind) -> Option<Blocker> {
    match kind {
        ErrorKind::DiskFull => Some(Blocker::DiskUnavailable),
        ErrorKind::VolumeMissing => Some(Blocker::VolumeMissing),
        _ => None,
    }
}

/// The explicit, retryable error shown while a job waits for disk space or its drive.
fn disk_error(e: &BackendError) -> ErrorData {
    ErrorData {
        kind: e.kind,
        retryable: true,
        next_action: if e.kind == ErrorKind::VolumeMissing {
            NextAction::ReconnectVolume
        } else {
            NextAction::FreeDiskSpace
        },
        detail: Some(e.detail.clone()),
    }
}

