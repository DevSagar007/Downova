    /// `queues.v1.delete` (ADR 0017): never deletes jobs or files. A queue with jobs (removed
    /// ones included, so a replay keeps its queue) needs `move_to`; the default queue stays.
    pub async fn delete_queue(&self, id: &str, move_to: Option<&str>) -> Result<(), ServiceError> {
        let mut guard = self.state.lock().await;
        let State {
            jobs,
            queues,
            store,
            ..
        } = &mut *guard;
        let refused = |why: &str| Err(ServiceError::new(ErrorKind::InvalidRequest, why));
        if id == DEFAULT_QUEUE {
            return refused("the main queue cannot be deleted");
        }
        find_queue(queues, id)?;
        let members = jobs.iter().filter(|j| j.queue_id == id).count();
        let target = match move_to {
            Some(t) if t == id => return refused("a queue cannot receive its own downloads"),
            Some(t) => Some(find_queue(queues, t)?.queue_id.clone()),
            None if members > 0 => {
                return refused("the queue still has downloads: choose a queue to move them to");
            }
            None => None,
        };
        if let Some(s) = store.as_mut() {
            s.delete_queue(id, target.as_deref()).map_err(|e| {
                eprintln!("dm-service: queue deletion not recorded: {e}");
                ServiceError::new(ErrorKind::Internal, "the queue could not be deleted")
                    .with_action(NextAction::Retry)
            })?;
        }
        if let Some(target) = target {
            let base = jobs
                .iter()
                .filter(|j| j.queue_id == target)
                .map(|j| j.queue_position)
                .max()
                .unwrap_or(0);
            for job in jobs.iter_mut().filter(|j| j.queue_id == id) {
                job.queue_id = target.clone();
                job.queue_position = base.saturating_add(job.queue_position);
            }
        }
        queues.retain(|q| q.queue_id != id);
        self.admit(jobs, queues, store).await;
        Ok(())
    }

    /// `queues.v1.start` / `queues.v1.stop` (B2.11). Stopping pauses the queue's running
    /// transfers (each checkpointed) and holds its unfinished jobs with `queue_stopped`;
    /// `desired_state` is never changed, and finalizing jobs finish. Starting releases the hold:
    /// jobs the user paused stay paused, disk holds and retry cool-downs keep waiting, and the
    /// rest are admitted within the limits. The running state is durable before the answer.
    pub async fn set_queue_running(
        &self,
        id: &str,
        running: bool,
    ) -> Result<QueueInfo, ServiceError> {
        let mut guard = self.state.lock().await;
        let State {
            jobs,
            queues,
            store,
            ..
        } = &mut *guard;
        let queue = find_queue(queues, id)?;
        let mut next = queue.clone();
        next.running = running;
        save_queue(store, &next)?;
        *queue = next.clone();
        for job in jobs.iter_mut().filter(|j| j.queue_id == id) {
            if job.phase.is_terminal() || job.phase == Phase::Verifying {
                continue;
            }
            if running {
                job.sync_queue_hold(true);
                if job.desired_state == DesiredState::Running
                    && job.pending.is_none()
                    && job.retry_at.is_none()
                    && !job.is_disk_blocked()
                {
                    job.queue(if job.attempt.is_some() {
                        Pending::Resume
                    } else {
                        Pending::Fresh
                    });
                }
            } else {
                if job.is_active()
                    && let Some(handle) = job.attempt.as_ref().map(|a| a.handle.clone())
                {
                    if let Err(e) = self.backend.pause(&handle).await {
                        eprintln!(
                            "dm-service: could not hold job {} for its stopped queue: {e}",
                            job.id
                        );
                    }
                    if let Ok(confirmed) = self.backend.progress(&handle).await {
                        job.downloaded = confirmed.completed;
                    }
                    self.take_checkpoint(store, job).await;
                    job.queue(Pending::Resume);
                }
                job.sync_queue_hold(false);
            }
            persist(store, job);
        }
        self.admit(jobs, queues, store).await;
        Ok(queue_info(&next))
    }

    /// `downloads.v1.set_queue`: the job moves to the end of another queue. A transfer keeps
    /// running in its new queue (counted there from now on, even above that queue's limit; no
    /// preemption) unless the new queue is stopped, which holds it like Stop queue does.
    pub async fn set_job_queue(
        &self,
        id: &JobId,
        queue_id: &str,
    ) -> Result<DownloadSnapshot, ServiceError> {
        let mut guard = self.state.lock().await;
        let State {
            jobs,
            queues,
            store,
            ..
        } = &mut *guard;
        let target = find_queue(queues, queue_id)?.clone();
        let base = jobs
            .iter()
            .filter(|j| j.queue_id == target.queue_id && &j.id != id)
            .map(|j| j.queue_position)
            .max()
            .unwrap_or(0);
        let job = find_job(jobs, id)?;
        if job.queue_id != target.queue_id {
            job.queue_id = target.queue_id.clone();
            job.queue_position = base.saturating_add(1);
            if !target.running
                && job.is_active()
                && let Some(handle) = job.attempt.as_ref().map(|a| a.handle.clone())
            {
                let _ = self.backend.pause(&handle).await;
                self.take_checkpoint(store, job).await;
                job.queue(Pending::Resume);
            }
            job.sync_queue_hold(target.running);
            persist(store, job);
        }
        let snapshot = find_job(jobs, id)?.snapshot();
        self.admit(jobs, queues, store).await;
        Ok(find_job(jobs, id).map(|j| j.snapshot()).unwrap_or(snapshot))
    }

